#!/usr/bin/env node
// Writes the text equivalent of the interactive YDB walkthrough into
// src/content/docs/extend/write-a-provider/ydb-walkthrough-explore.mdx,
// between its two markers, from the declaration both views read
// (src/ydb-walkthrough.mjs).
//
// The text is in the page itself, not rendered by a component, because the
// page's Markdown copy is its source: a component tag there would hide every
// fact from a reader who copies the page. Generating it keeps that copy and
// the interactive figure from disagreeing.
//
// Usage:
//   node scripts/build-ydb-walkthrough.mjs            # rewrite the section
//   node scripts/build-ydb-walkthrough.mjs --check    # fail if it is stale
//   node scripts/build-ydb-walkthrough.mjs --selftest # check the splice itself
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { walkthroughMarkdown } from '../src/ydb-walkthrough.mjs';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const pagePath = join(scriptDir, '..', 'src', 'content', 'docs', 'extend', 'write-a-provider', 'ydb-walkthrough-explore.mdx');
const begin = '{/* Generated by scripts/build-ydb-walkthrough.mjs from src/ydb-walkthrough.mjs. Do not edit by hand. */}';
const end = '{/* End of the generated walkthrough text. */}';

/** The page with the section between the markers replaced by text. */
export function splice(page, text) {
  const start = page.indexOf(begin);
  const stop = page.indexOf(end);
  if (start === -1 || stop === -1 || stop < start || page.indexOf(begin, start + 1) !== -1 || page.indexOf(end, stop + 1) !== -1) {
    throw new Error('build-ydb-walkthrough.mjs: the page needs each marker exactly once, the begin marker first');
  }
  return `${page.slice(0, start + begin.length)}\n\n${text}\n${page.slice(stop)}`;
}

function selftest() {
  const page = `intro\n\n${begin}\n\nold\n\n${end}\n\nafter\n`;
  const spliced = splice(page, 'new\n');
  if (spliced !== `intro\n\n${begin}\n\nnew\n\n${end}\n\nafter\n`) throw new Error('selftest: the splice did not replace the section');
  if (splice(spliced, 'new\n') !== spliced) throw new Error('selftest: a second splice changed the page');
  for (const broken of [`${begin}\n${end}\n${end}`, `${end}\n${begin}`, 'no markers']) {
    let refused = false;
    try {
      splice(broken, 'x');
    } catch {
      refused = true;
    }
    if (!refused) throw new Error(`selftest: a page with misplaced markers was accepted: ${JSON.stringify(broken)}`);
  }
  if (!walkthroughMarkdown().includes('| Normal creation |')) throw new Error('selftest: the text has no scenario rows');
  console.log('build-ydb-walkthrough.mjs --selftest: OK (splice, idempotence, misplaced markers, scenario rows)');
}

if (process.argv.includes('--selftest')) {
  selftest();
} else {
  const current = readFileSync(pagePath, 'utf8');
  const page = splice(current, walkthroughMarkdown());
  if (process.argv.includes('--check')) {
    if (page !== current) {
      console.error('build-ydb-walkthrough.mjs --check: the walkthrough text is stale; run node docs/site/scripts/build-ydb-walkthrough.mjs');
      process.exit(1);
    }
    console.log('build-ydb-walkthrough.mjs --check: OK');
  } else {
    writeFileSync(pagePath, page);
    console.log('build-ydb-walkthrough.mjs: wrote the walkthrough text');
  }
}
