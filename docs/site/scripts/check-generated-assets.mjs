#!/usr/bin/env node
// Regenerate the committed product samples and fail when any of them changed.
//
// Three consecutive changes shipped a sample describing output the binary no
// longer wrote: stokaro/ptah#2866 left four report samples behind, #2899 found
// them, and #2903 left seven more. Nothing compared these files, so every one
// of them was green. The obligation was prose in AGENTS.md and in
// docs/site/src/assets/schema-ui.source.md, and prose is a thing to remember.
//
// This governs the TEXT samples under docs/site/public/samples, not the PNGs
// beside them. The samples are what the binary itself produced, byte for byte
// on any machine; a screenshot is a browser rendering whose pixels differ with
// the platform's fonts, which is why check-visual-snapshots.mjs deliberately
// keeps no pixel baseline. That costs nothing here: every one of the three
// misses changed a sample, because a Ptah HTML document carries its whole
// stylesheet inline, so an appearance change is a text change.
//
// It needs what the generators need: a built binary in PTAH_BIN, a Playwright
// browser, and Graphviz for the visualize samples. A missing one surfaces as
// the generator's own refusal and a non-zero exit, which this reports rather
// than reading as a clean tree.
import { spawnSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const siteRoot = join(scriptDir, '..');
const repositoryRoot = join(siteRoot, '..', '..');

// The samples this gate owns. The inference quick-start bundle sits in the same
// directory and is written by build-inference-quick-start.mjs, which needs a
// Docker daemon; docs/site/scripts/check-inference-quick-start.sh covers it.
const GOVERNED = 'docs/site/public/samples';
const NOT_OURS = [
  'docs/site/public/samples/inference-quick-start.zip',
  'docs/site/public/samples/inference-quick-start.zip.sha256',
  // Graphviz drew these, not Ptah. The bytes carry the renderer's version
  // string -- "Generated by graphviz version 14.1.5" -- and its font metrics
  // decide every coordinate, so they differ between a developer's machine and
  // the runner for a reason that has nothing to do with freshness. This is not
  // a hole: `ptah viz --format dot` writes schema.dot and schema-security.dot
  // beside them, those are Ptah's own output, and they stay governed. The one
  // thing it cannot see is a change to the arguments Ptah passes dot, which
  // would move the SVG without moving the DOT.
  'docs/site/public/samples/visualize/schema-dot.svg',
  'docs/site/public/samples/visualize/schema-security.svg',
];

// The floor is a source constant rather than a count read out of the tree,
// because a glob that stopped matching reports zero differences and a gate that
// compares nothing reports success. Raising it is a reviewed edit.
const CORPUS_FLOOR = 20;

// What the governed corpus excludes and why is above, in NOT_OURS. Everything
// left is a file the Ptah binary wrote byte for byte, so it is the same on
// every machine.

const GENERATORS = ['generate-schema-ui-assets.mjs', 'generate-product-output-assets.mjs'];

// analyze is the whole decision, separated from running anything so the
// selftest can hand it the failures a green run never produces.
export function analyze({ dirtyBefore, generators, corpus, changed }) {
  const problems = [];

  for (const path of dirtyBefore ?? []) {
    problems.push(`${path} is already modified; commit or revert it before checking freshness`);
  }

  const ran = generators ?? [];
  if (ran.length !== GENERATORS.length) {
    problems.push(`expected ${GENERATORS.length} generators to run, saw ${ran.length}`);
  }
  for (const generator of ran) {
    if (generator.status !== 0) {
      problems.push(`${generator.name} exited ${generator.status}; a generator that wrote nothing leaves a clean tree`);
    }
  }

  if ((corpus ?? 0) < CORPUS_FLOOR) {
    problems.push(`found ${corpus ?? 0} governed samples, below the floor of ${CORPUS_FLOOR}; the gate compared almost nothing`);
  }

  for (const path of changed ?? []) {
    problems.push(`${path} is stale: regenerating it produced different bytes`);
  }

  return problems;
}

function git(args) {
  const result = spawnSync('git', args, { cwd: repositoryRoot, encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${result.stderr}`);
  return result.stdout;
}

function governedPaths(porcelainOrList) {
  return porcelainOrList
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => (line.includes(' ') ? line.slice(line.indexOf(' ') + 1).trim() : line))
    .filter((path) => !NOT_OURS.includes(path));
}

function selftest() {
  const green = {
    dirtyBefore: [],
    generators: GENERATORS.map((name) => ({ name, status: 0 })),
    corpus: CORPUS_FLOOR + 2,
    changed: [],
  };
  if (analyze(green).length > 0) {
    console.error('check-generated-assets.mjs --selftest: FAILED (rejected a healthy run)');
    process.exitCode = 1;
    return;
  }

  const cases = [
    ['a crashed generator', { ...green, generators: [{ name: GENERATORS[0], status: 1 }, { name: GENERATORS[1], status: 0 }] }, 'exited 1'],
    ['a generator that never ran', { ...green, generators: [{ name: GENERATORS[0], status: 0 }] }, 'saw 1'],
    ['a corpus below the floor', { ...green, corpus: 1 }, 'below the floor'],
    ['a stale sample', { ...green, changed: ['docs/site/public/samples/schema-document.html'] }, 'is stale'],
    ['a tree that was already dirty', { ...green, dirtyBefore: ['docs/site/public/samples/schema-document.html'] }, 'already modified'],
  ];
  for (const [label, input, expected] of cases) {
    const problems = analyze(input);
    if (!problems.some((problem) => problem.includes(expected))) {
      console.error(`check-generated-assets.mjs --selftest: FAILED (did not reject ${label})`);
      process.exitCode = 1;
      return;
    }
  }
  console.log(`check-generated-assets.mjs --selftest: OK (${cases.length} broken runs rejected, healthy run accepted)`);
}

function run() {
  const binary = process.env.PTAH_BIN;
  if (!binary || !existsSync(binary)) {
    console.error(`check-generated-assets.mjs: PTAH_BIN must name a built binary (got ${binary ?? 'nothing'})`);
    process.exitCode = 1;
    return;
  }

  const dirtyBefore = governedPaths(git(['status', '--porcelain', '--', GOVERNED]));
  const generators = [];
  if (dirtyBefore.length === 0) {
    for (const name of GENERATORS) {
      const result = spawnSync('node', [join(scriptDir, name)], {
        cwd: siteRoot,
        encoding: 'utf8',
        env: { ...process.env, PTAH_BIN: binary },
        stdio: ['ignore', 'inherit', 'inherit'],
      });
      generators.push({ name, status: result.status });
    }
  }

  const corpus = governedPaths(git(['ls-files', '--', GOVERNED])).length;
  const changed = governedPaths(git(['status', '--porcelain', '--', GOVERNED]));
  const problems = analyze({ dirtyBefore, generators, corpus, changed });

  if (problems.length > 0) {
    console.error('check-generated-assets.mjs: FAILED');
    for (const problem of problems) console.error(`- ${problem}`);
    console.error('');
    console.error('This run already regenerated them, so the current bytes are in your working');
    console.error('tree: review the diff and commit it. The screenshots beside them moved too,');
    console.error('and this gate does not compare those -- look at them before you commit.');
    process.exitCode = 1;
    return;
  }
  console.log(`check-generated-assets.mjs: OK (${GENERATORS.length} generators, ${corpus} samples match what the binary writes)`);
}

if (process.argv.includes('--selftest')) selftest();
else run();
