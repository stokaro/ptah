package coverage_test

import (
	"fmt"
	"strings"

	"go.5x5.cz/ptah/core/coverage"
)

// Example walks the whole story end to end: a reader that was refused the
// extension catalog and never read the "extra" schema records both limits,
// serializes them into the comment header of the document it writes, and a
// second process decodes the header and consults it before planning. The
// directive lines are exactly what [coverage.Set.Directives] returns;
// [coverage.Set.Normalize] sorts and deduplicates them, so the bytes are
// deterministic.
func Example() {
	set := coverage.Set{}.
		With(coverage.Refused(coverage.Extension)).
		WithObject(coverage.Schema, "extra")

	var document strings.Builder
	for _, directive := range set.Directives() {
		fmt.Fprintf(&document, "-- %s\n", directive)
	}
	document.WriteString("\nCREATE TABLE users (id BIGINT PRIMARY KEY);\n")
	fmt.Print(document.String())

	decoded, err := coverage.DecodeHeader(document.String())
	if err != nil {
		fmt.Println("decode:", err)
		return
	}

	// The absence of an extension is uninformative: the whole kind was refused.
	fmt.Println("describes extension pg_trgm:", decoded.Describes(coverage.Extension, "pg_trgm"))
	// A sequence in the unread schema is not described either.
	fmt.Println("describes sequence extra.ids:", decoded.DescribesIn(coverage.Sequence, "extra", "ids"))
	// A sequence in a described schema is: its absence is authoritative.
	fmt.Println("describes sequence public.ids:", decoded.DescribesIn(coverage.Sequence, "public", "ids"))

	// Output:
	// -- ptah:not-described extension reason=not-inspected provenance=observed
	// -- ptah:not-described schema "extra"
	//
	// CREATE TABLE users (id BIGINT PRIMARY KEY);
	// describes extension pg_trgm: false
	// describes sequence extra.ids: false
	// describes sequence public.ids: true
}

// ExampleSet_Describes shows the three-state model as answers to one question:
// may a comparator act on this object's absence? The zero Set claims
// everything; a whole-kind record makes every absence of that kind
// uninformative; a named record limits only the object it names -- and only
// under a spelling the caller supplies, which is why the variadic takes every
// spelling the two sides of a comparison might use.
func ExampleSet_Describes() {
	var set coverage.Set
	fmt.Println(set.Describes(coverage.Extension, "pg_trgm"))

	set = set.WithKind(coverage.Extension)
	fmt.Println(set.Describes(coverage.Extension, "pg_trgm"))

	set = set.WithObject(coverage.Sequence, "billing.invoice_ids")
	fmt.Println(set.Describes(coverage.Sequence, "invoice_ids"))
	fmt.Println(set.Describes(coverage.Sequence, "billing.invoice_ids", "invoice_ids"))

	set = set.WithObject(coverage.Schema, "reporting")
	fmt.Println(set.DescribesSchema("reporting"))
	fmt.Println(set.DescribesIn(coverage.Sequence, "reporting", "ids"))

	// Output:
	// true
	// false
	// true
	// false
	// false
	// false
}

// ExampleDecodeHeader parses the leading comment header of a SQL document: a
// directive carrying its reason and provenance, one naming a quoted identifier
// with a space in it, and an ordinary comment that is passed over rather than
// refused. The directive after the first content line is deliberately not
// read -- a directive recognized anywhere in the file could be smuggled in
// through a string literal -- so the sequence kind stays described.
//
// The error is not decoration. A directive this build cannot read is refused
// rather than ignored, and a caller that swallows the refusal is back to
// reading an unintelligible limit as no limit at all, which is the removal
// this package exists to prevent.
func ExampleDecodeHeader() {
	document := `-- ptah:not-described extension reason=not-inspected provenance=observed
-- ptah:not-described schema "extra reports"
-- generated by an inspection that was refused the extension catalog

CREATE TABLE users (id BIGINT PRIMARY KEY);

-- ptah:not-described sequence
`
	set, err := coverage.DecodeHeader(document)
	if err != nil {
		fmt.Println("refused:", err)
		return
	}

	for _, directive := range set.Directives() {
		fmt.Println(directive)
	}
	fmt.Println("describes sequences:", set.Describes(coverage.Sequence, "user_ids"))

	// Output:
	// ptah:not-described extension reason=not-inspected provenance=observed
	// ptah:not-described schema "extra reports"
	// describes sequences: true
}

// ExampleObject_Explain renders the shared diagnostic vocabulary: every
// surface that has to explain an uninformative absence calls Explain rather
// than wording the sentence itself, so the same record reads the same way in
// every command. A record that gives no reason yields an empty clause -- a
// hand-authored directive naming only a kind said no more than that.
func ExampleObject_Explain() {
	refused := coverage.Refused(coverage.Extension)
	fmt.Printf("%q\n", refused.Explain())

	scoped := coverage.Object{
		Kind:       coverage.Schema,
		Reason:     coverage.OutsideScope,
		Provenance: coverage.Configured,
	}
	fmt.Printf("%q\n", scoped.Explain())

	bare := coverage.Object{Kind: coverage.Sequence}
	fmt.Printf("%q\n", bare.Explain())

	// Output:
	// "the read was refused the catalog that would have listed them"
	// "the selection this run was given put them outside it"
	// ""
}
