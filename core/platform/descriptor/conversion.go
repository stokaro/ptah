package descriptor

// Conversion states what the readers and converters of schema documents --
// Go annotations, YAML, schema files, catalogs read back, imported
// migrations -- read of an engine where engines differ. The zero value
// gives none of these conventions.
type Conversion struct {
	// PropertyShortcuts reports that a table directive's `engine` and
	// `comment` attributes, and a field's comment, are platform properties of
	// the engine, read without the platform.<dialect> prefix.
	PropertyShortcuts bool `json:"property_shortcuts,omitempty"`
	// SerialForeignKeyType is the type an embedded relation's INTEGER foreign
	// key column is written as, for an engine whose serial key is that type,
	// such as "INT". Empty keeps INTEGER.
	SerialForeignKeyType string `json:"serial_foreign_key_type,omitempty"`
	// RowFormatProperty reports that a table's row format is a platform
	// property of the engine, kept when a catalog is converted back to a
	// declaration so an index hint that needs it can be replayed.
	RowFormatProperty bool `json:"row_format_property,omitempty"`
	// ConstraintComments reports that a primary key constraint carries a
	// comment of its own, which a converted declaration keeps.
	ConstraintComments bool `json:"constraint_comments,omitempty"`
	// RowPolicyOwned reports that a row-level security declaration scoped to
	// the engine is the engine owner's row policy rather than the shared
	// row-level security model.
	RowPolicyOwned bool `json:"row_policy_owned,omitempty"`
	// RowLevelSecurity reports that the engine holds the shared row-level
	// security model, whose declarations name their table by the engine's
	// identifier rules.
	RowLevelSecurity bool `json:"row_level_security,omitempty"`
	// EmptyPolicyRolesArePublic reports that a row-level security policy that
	// names no role applies to PUBLIC, as its reader reports it.
	EmptyPolicyRolesArePublic bool `json:"empty_policy_roles_are_public,omitempty"`
	// AutoIncrementIdentity reports that an imported auto-increment column is
	// an identity generated BY DEFAULT, the one spelling that keeps the
	// declared type.
	AutoIncrementIdentity bool `json:"auto_increment_identity,omitempty"`
	// DatabaseRootPaths reports that a schema document names objects by
	// absolute paths under the database root its URL names.
	DatabaseRootPaths bool `json:"database_root_paths,omitempty"`
	// OwnedSequences reports that a column declared with a serial type owns
	// the sequence that fills it, which a read reports.
	OwnedSequences bool `json:"owned_sequences,omitempty"`
	// ImplicitRoutineGrants reports that every routine carries EXECUTE for
	// PUBLIC unless revoked, which a read reports.
	ImplicitRoutineGrants bool `json:"implicit_routine_grants,omitempty"`
	// IndexTypeIsMethod reports that an index's declared type is its access
	// method, as a read reports it.
	IndexTypeIsMethod bool `json:"index_type_is_method,omitempty"`
}
