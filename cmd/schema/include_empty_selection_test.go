package schema_test

import (
	"bytes"
	"os"
	"path/filepath"
	"regexp"
	"testing"

	qt "github.com/frankban/quicktest"

	"go.5x5.cz/ptah/cmd/schema"
)

// nativeEmptySelectionDDL is the fixture the native-surface rows select
// against: one plainly named table and one whose name literally holds dots.
const nativeEmptySelectionDDL = `CREATE TABLE native_sel_users (id INTEGER PRIMARY KEY, email TEXT);
CREATE TABLE "a.b.c" (id INTEGER PRIMARY KEY);`

// runSchemaStreams executes a native schema subcommand with standard output
// and standard error kept apart, so a row can prove the notice landed out of
// band rather than in the plan.
func runSchemaStreams(args ...string) (stdout, stderr string, err error) {
	cmd := schema.NewSchemaCommand()
	var out, errOut bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&errOut)
	cmd.SetArgs(args)
	err = cmd.Execute()
	return out.String(), errOut.String(), err
}

// TestNativeSchemaVerbsDivergeOnAnEmptyIncludeSelection pins the divergence on
// the native surface, which shares one implementation with the Atlas-shaped
// one: diff and inspect keep their exit status and report the empty selection
// on standard error, while apply refuses.
//
// The divergence is deliberate rather than copied. The pinned Atlas community
// binary implements no --include flag, so there is no oracle for it; its
// sibling positive selector --schema answers a zero match with exit 0 and
// silence on every verb, which is where diff and inspect stay. Apply is the
// one verb where silence means a target was left untouched while the command
// claimed success.
func TestNativeSchemaVerbsDivergeOnAnEmptyIncludeSelection(t *testing.T) {
	c := qt.New(t)

	tests := []struct {
		name string
		// run executes one verb against the shared fixture and returns its
		// streams, so each verb supplies its own flag spellings.
		run func(dbPath, schemaPath, devPath string) (stdout, stderr string, err error)
		// wantStdout is the exact output the verb must still produce.
		wantStdout string
		// wantErr is the exact error text, empty when the verb keeps exit 0.
		wantErr string
	}{
		{
			name: "diff reports and continues",
			run: func(_, schemaPath, devPath string) (string, string, error) {
				emptyPath := filepath.Join(filepath.Dir(schemaPath), "empty.sql")
				writeErr := os.WriteFile(emptyPath, []byte(""), 0o600)
				c.Assert(writeErr, qt.IsNil)
				return runSchemaStreams("diff",
					"--from", "file://"+emptyPath,
					"--to", "file://"+schemaPath,
					"--dev-url", "sqlite://"+devPath,
					"--include", "no_such_table",
				)
			},
			wantStdout: "Schemas are synced, no changes to be made.\n",
		},
		{
			name: "inspect reports and continues",
			run: func(dbPath, _, _ string) (string, string, error) {
				return runSchemaStreams("inspect",
					"--db-url", "sqlite://"+dbPath,
					"--include", "no_such_table",
				)
			},
			wantStdout: "// Code generated by ptah; DO NOT EDIT.\n\n",
		},
		{
			name: "apply refuses",
			run: func(dbPath, schemaPath, _ string) (string, string, error) {
				return runSchemaStreams("apply",
					"--db-url", "sqlite://"+dbPath,
					"--schema-file", schemaPath,
					"--include", "no_such_table",
					"--dry-run",
				)
			},
			wantErr: `the --include selection matched no objects: "no_such_table"; schema apply would change nothing`,
		},
	}

	for _, test := range tests {
		c.Run(test.name, func(c *qt.C) {
			dir := t.TempDir()
			dbPath := filepath.Join(dir, "live.db")
			seedSQLite(c, dbPath, nativeEmptySelectionDDL)
			schemaPath := writeSchemaSQLFile(c, dir, "schema.sql", nativeEmptySelectionDDL+"\n")

			stdout, stderr, err := test.run(dbPath, schemaPath, filepath.Join(dir, "dev.db"))

			c.Assert(errorText(err), qt.Matches, regexp.QuoteMeta(test.wantErr))
			c.Assert(stdout, qt.Equals, test.wantStdout)
			c.Assert(stderr, qt.Contains, `the --include selection matched no objects: "no_such_table"`)
		})
	}
}

// errorText renders an error for exact comparison, so a row pins the bytes of
// the message and the absence of one with a single assertion.
func errorText(err error) string {
	if err == nil {
		return ""
	}
	return err.Error()
}
