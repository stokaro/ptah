const (
	dropDefaultReason  = "DROP DEFAULT can break writers that leave the column out"
	dropIdentityReason = "DROP IDENTITY removes the sequence that fills the column and its position; " +
		"an insert that leaves the column out fails, and one created again can hand out a key a row already holds"
	generatedAlwaysReason    = "GENERATED ALWAYS refuses an insert that names the column"
	generatedByDefaultReason = "GENERATED BY DEFAULT accepts an insert that names the column, " +
		"and a value it names can collide with one the sequence hands out later"
)

// modifyColumn is the node a planner builds for a change of t.c.
func modifyColumn(op *ast.ModifyColumnOperation) *ast.AlterTableNode {
	return &ast.AlterTableNode{Name: "t", Operations: []ast.AlterOperation{op}}
}

// nullableColumn is t.c of columnType, holding no default.
func nullableColumn(columnType string) *ast.ColumnNode {
	column := ast.NewColumn("c", columnType)
	column.Nullable = true
	return column
}

// TestClassify_ATemporalTypeThatNarrows pins the node's verdict. A precision both sides
// declare needs no engine, and one that only one side declares takes the answer the
// comparison established on the engine.
func TestClassify_ATemporalTypeThatNarrows(t *testing.T) {
	tests := []struct {
		name string
		op   *ast.ModifyColumnOperation
		want safety.Severity
	}{
		{
			name: "both declare, down",
			op:   &ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp(0)"), PreviousType: "timestamp(6)"},
			want: safety.Destructive,
		},
		{
			name: "both declare, up",
			op:   &ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp(6)"), PreviousType: "timestamp(0)"},
			want: safety.Warning,
		},
		{
			name: "one declares, and the comparison says it narrows",
			op:   &ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp"), PreviousType: "timestamp(6)", TypeNarrows: true},
			want: safety.Destructive,
		},
		{
			name: "one declares, and the comparison says nothing",
			op:   &ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp"), PreviousType: "timestamp(3)"},
			want: safety.Warning,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			c.Assert(safety.Classify(modifyColumn(test.op)), qt.Equals, test.want)
		})
	}
}

// TestClassify_AColumnThatLosesItsIdentity is judged at the node, where a plan that
// drops the identity and a NOT NULL together cannot read as one that only relaxes the
// column.
func TestClassify_AColumnThatLosesItsIdentity(t *testing.T) {
	c := qt.New(t)

	assessments := safety.Assess([]ast.Node{modifyColumn(&ast.ModifyColumnOperation{
		Column:     ast.NewColumn("c", "bigint"),
		Changed:    ast.ColumnProperties{Identity: true},
		HasChanged: true,
	})})

	c.Assert(assessments, qt.HasLen, 1)
	c.Assert(assessments[0].Severity, qt.Equals, safety.Destructive)
	c.Assert(assessments[0].Reason, qt.Equals, dropIdentityReason)
}

// TestAssessSQL_WhatAnInsertDoesAfterTheStatement rates the statements the serial and
// identity comparisons plan. Each row loses no stored row, and a later insert behaves
// differently. The controls say what the words must not catch: a generated column that
// is added, and a string that holds the words.
func TestAssessSQL_WhatAnInsertDoesAfterTheStatement(t *testing.T) {
	tests := []struct {
		name       string
		statement  string
		wantRating safety.Severity
		wantReason string
	}{
		{"DROP IDENTITY", `ALTER TABLE "t" ALTER COLUMN "c" DROP IDENTITY`, safety.Destructive, dropIdentityReason},
		{"DROP IDENTITY IF EXISTS", `ALTER TABLE "t" ALTER COLUMN "c" DROP IDENTITY IF EXISTS`, safety.Destructive, dropIdentityReason},
		{"DROP DEFAULT", `ALTER TABLE "t" ALTER COLUMN "c" DROP DEFAULT`, safety.Warning, dropDefaultReason},
		{"SET GENERATED ALWAYS", `ALTER TABLE "t" ALTER COLUMN "c" SET GENERATED ALWAYS`, safety.Warning, generatedAlwaysReason},
		{"SET GENERATED BY DEFAULT", `ALTER TABLE "t" ALTER COLUMN "c" SET GENERATED BY DEFAULT`, safety.Warning, generatedByDefaultReason},
		{"ADD GENERATED ALWAYS", `ALTER TABLE "t" ALTER COLUMN "c" ADD GENERATED ALWAYS AS IDENTITY`, safety.Warning, generatedAlwaysReason},
		{"ADD GENERATED BY DEFAULT", `ALTER TABLE "t" ALTER COLUMN "c" ADD GENERATED BY DEFAULT AS IDENTITY`, safety.Safe, safeReason},
		{"SET DEFAULT", `ALTER TABLE "t" ALTER COLUMN "c" SET DEFAULT 7`, safety.Safe, safeReason},
		{"an added generated column", `ALTER TABLE "t" ADD COLUMN "g" bigint GENERATED ALWAYS AS IDENTITY`, safety.Safe, safeReason},
		{"a string that holds the words", `ALTER TABLE "t" ALTER COLUMN "c" SET DEFAULT 'DROP IDENTITY'`, safety.Safe, safeReason},
		{"a comment above the statement", "-- Modify column t.c\nALTER TABLE \"t\" ALTER COLUMN \"c\" DROP IDENTITY", safety.Destructive, dropIdentityReason},
		{"a comment that holds the words", "-- DROP IDENTITY\nALTER TABLE \"t\" ALTER COLUMN \"c\" SET DEFAULT 7", safety.Safe, safeReason},
		{
			"a routine body that holds the words",
			"CREATE FUNCTION f() RETURNS void AS $$ BEGIN ALTER TABLE t ALTER COLUMN c DROP DEFAULT; END $$ LANGUAGE plpgsql",
			safety.Safe, safeReason,
		},
		{"a table named by the words", `CREATE TABLE drop_identity (id int PRIMARY KEY)`, safety.Safe, safeReason},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			got := assessText(c, "postgres", test.statement)
			c.Assert(got.Severity, qt.Equals, test.wantRating)
			c.Assert(got.Reason, qt.Equals, test.wantReason)
		})
	}
}

// TestColumnVerdicts_HappyPath reads a verdict the statement's words cannot give. The
// MySQL rows are why it is by node: MODIFY COLUMN restates the column, and reads the same
// whatever it gives up.
func TestColumnVerdicts_HappyPath(t *testing.T) {
	notNullDropped := "DROP NOT NULL removes a column-level data protection"
	tests := []struct {
		name       string
		op         *ast.ModifyColumnOperation
		statement  string
		wantRating safety.Severity
		wantReason string
	}{
		{
			name:       "a temporal precision goes down",
			op:         &ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp(0)"), PreviousType: "timestamp(6)"},
			statement:  `ALTER TABLE "t" ALTER COLUMN "c" TYPE timestamp(0)`,
			wantRating: safety.Destructive,
			wantReason: "column type narrows from timestamp(6) to timestamp(0)",
		},
		{
			name:       "the comparison says a bare type narrows",
			op:         &ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp"), PreviousType: "timestamp(6)", TypeNarrows: true},
			statement:  "ALTER TABLE `t` MODIFY COLUMN `c` timestamp",
			wantRating: safety.Destructive,
			wantReason: "column type narrows from timestamp(6) to timestamp",
		},
		{
			name:       "a string gets shorter",
			op:         &ast.ModifyColumnOperation{Column: ast.NewColumn("c", "varchar(5)"), PreviousType: "varchar(100)"},
			statement:  `ALTER TABLE "t" ALTER COLUMN "c" TYPE varchar(5)`,
			wantRating: safety.Destructive,
			wantReason: "column type narrows from varchar(100) to varchar(5)",
		},
		{
			name: "a restated column gives up NOT NULL",
			op: &ast.ModifyColumnOperation{
				Column:              nullableColumn("bigint"),
				HasPreviousNullable: true,
				Changed:             ast.ColumnProperties{Nullability: true},
				HasChanged:          true,
			},
			statement:  "ALTER TABLE `t` MODIFY COLUMN `c` bigint",
			wantRating: safety.Destructive,
			wantReason: notNullDropped,
		},
		{
			name: "a restated column gives up its default",
			op: &ast.ModifyColumnOperation{
				Column: nullableColumn("bigint"), Changed: ast.ColumnProperties{Default: true}, HasChanged: true,
			},
			statement:  "ALTER TABLE `t` MODIFY COLUMN `c` bigint",
			wantRating: safety.Warning,
			wantReason: dropDefaultReason,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			verdicts, err := safety.ColumnVerdicts([]ast.Node{modifyColumn(test.op)}, []int{0}, []string{test.statement})

			c.Assert(err, qt.IsNil)
			c.Assert(verdicts, qt.HasLen, 1)
			c.Assert(verdicts[0].Severity, qt.Equals, test.wantRating)
			c.Assert(verdicts[0].Reason, qt.Equals, test.wantReason)
		})
	}
}

// TestColumnVerdicts_LeavesTheRestToTheWords holds the fold to what the words cannot
// say. A change a statement reports by being there stays out of it, and so does a node
// that is not a column change: a plan that replaces a view has its own reading of the
// DROP VIEW, which a node's verdict would raise back.
func TestColumnVerdicts_LeavesTheRestToTheWords(t *testing.T) {
	tests := []struct {
		name      string
		node      ast.Node
		statement string
	}{
		{
			name:      "a widening",
			node:      modifyColumn(&ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp(6)"), PreviousType: "timestamp(3)"}),
			statement: `ALTER TABLE "t" ALTER COLUMN "c" TYPE timestamp(6)`,
		},
		{
			name:      "an unrelated type change",
			node:      modifyColumn(&ast.ModifyColumnOperation{Column: ast.NewColumn("c", "text"), PreviousType: "int"}),
			statement: `ALTER TABLE "t" ALTER COLUMN "c" TYPE text`,
		},
		{
			name:      "another operation of an ALTER TABLE",
			node:      &ast.AlterTableNode{Name: "t", Operations: []ast.AlterOperation{&ast.DropConstraintOperation{ConstraintName: "fk"}}},
			statement: "ALTER TABLE `t` DROP FOREIGN KEY `fk`",
		},
		{name: "a dropped view", node: ast.NewDropView("v"), statement: `DROP VIEW "v"`},
		{name: "a dropped table", node: ast.NewDropTable("t"), statement: `DROP TABLE "t"`},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			verdicts, err := safety.ColumnVerdicts([]ast.Node{test.node}, []int{0}, []string{test.statement})

			c.Assert(err, qt.IsNil)
			c.Assert(verdicts, qt.DeepEquals, []safety.StatementAssessment{{}})
		})
	}
}

// TestColumnVerdicts_ANodeThatRendersSeveralStatements gives the verdict to the
// statement that changes the type. A SET DEFAULT beside it did not narrow anything.
func TestColumnVerdicts_ANodeThatRendersSeveralStatements(t *testing.T) {
	c := qt.New(t)
	node := modifyColumn(&ast.ModifyColumnOperation{Column: ast.NewColumn("c", "timestamp(0)"), PreviousType: "timestamp(6)"})

	verdicts, err := safety.ColumnVerdicts(
		[]ast.Node{ast.NewDropTable("other"), node},
		[]int{-1, 1, 1},
		[]string{"SELECT 1", `ALTER TABLE "t" ALTER COLUMN "c" TYPE timestamp(0)`, `ALTER TABLE "t" ALTER COLUMN "c" SET DEFAULT now()`},
	)

	c.Assert(err, qt.IsNil)
	c.Assert(verdicts, qt.HasLen, 3)
	c.Assert(verdicts[0], qt.Equals, safety.StatementAssessment{})
	c.Assert(verdicts[1].Severity, qt.Equals, safety.Destructive)
	c.Assert(verdicts[2], qt.Equals, safety.StatementAssessment{})
}

func TestColumnVerdicts_FailurePath(t *testing.T) {
	tests := []struct {
		name       string
		provenance []int
		statements []string
	}{
		{name: "a node past the end", provenance: []int{1}, statements: []string{"SELECT 1"}},
		{name: "below the no-node mark", provenance: []int{-2}, statements: []string{"SELECT 1"}},
		{name: "lists of two lengths", provenance: []int{0}, statements: []string{"SELECT 1", "SELECT 2"}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			verdicts, err := safety.ColumnVerdicts([]ast.Node{ast.NewDropTable("t")}, test.provenance, test.statements)

			c.Assert(err, qt.ErrorIs, renderer.ErrInvalidResult)
			c.Assert(verdicts, qt.IsNil)
		})
	}
}

// TestAssess_ThePlannerCarriesTheComparisonsAnswer plans the same column change for each
// engine with and without the comparison's answer. The transition declares a precision
// on one side only, so nothing else in the plan can give that answer.
func TestAssess_ThePlannerCarriesTheComparisonsAnswer(t *testing.T) {
	dialects := []string{"postgres", "cockroachdb", "yugabytedb", "mysql", "mariadb", "sqlserver"}
	answers := []struct {
		name    string
		narrows bool
		want    safety.Severity
	}{
		{name: "narrows", narrows: true, want: safety.Destructive},
		{name: "does not narrow", narrows: false, want: safety.Warning},
	}
	for _, dialect := range dialects {
		for _, answer := range answers {
			t.Run(dialect+"/"+answer.name, func(t *testing.T) {
				c := qt.New(t)
				runtime := must.Must(builtin.New())
				diff := &difftypes.SchemaDiff{TablesModified: []difftypes.TableDiff{{
					TableName: "t",
					ColumnsModified: []difftypes.ColumnDiff{{
						ColumnName:  "c",
						TypeNarrows: answer.narrows,
						Desired:     schemamodel.Field{Name: "c", Type: "timestamp", StructName: "T", Nullable: true},
						Changes:     map[string]string{"type": "timestamp(6) -> timestamp"},
					}},
				}}}

				nodes, err := planner.GenerateSchemaDiffAST(c.Context(), runtime, diff, dialect)

				c.Assert(err, qt.IsNil)
				c.Assert(safety.HighestAssessment(safety.Assess(nodes)), qt.Equals, answer.want)
			})
		}
	}
}

// TestClassifySchemaDiff_CountsWhatThePlanRatesDestructive holds the drift report to the
// plan. A check at --severity destructive reads these categories, and columns_modified
// alone is a warning.
func TestClassifySchemaDiff_CountsWhatThePlanRatesDestructive(t *testing.T) {
	const modified = "columns_modified"
	tests := []struct {
		name   string
		column difftypes.ColumnDiff
		want   []safety.Finding
	}{
		{
			name:   "the comparison says a bare type narrows",
			column: difftypes.ColumnDiff{TypeNarrows: true, Changes: map[string]string{"type": "timestamp(6) -> timestamp"}},
			want: []safety.Finding{
				{Category: "column_types_narrowed", Count: 1, Severity: safety.Destructive},
				{Category: modified, Count: 1, Severity: safety.Warning},
			},
		},
		{
			name:   "a diff assembled by hand, with both sides declared",
			column: difftypes.ColumnDiff{Changes: map[string]string{"type": "timestamp(6) -> timestamp(0)"}},
			want: []safety.Finding{
				{Category: "column_types_narrowed", Count: 1, Severity: safety.Destructive},
				{Category: modified, Count: 1, Severity: safety.Warning},
			},
		},
		{
			name:   "the entry's folded spelling is not what the column holds",
			column: difftypes.ColumnDiff{PreviousType: "varchar(5)", Changes: map[string]string{"type": "varchar -> char(10)"}},
			want:   []safety.Finding{{Category: modified, Count: 1, Severity: safety.Warning}},
		},
		{
			name:   "a widening",
			column: difftypes.ColumnDiff{Changes: map[string]string{"type": "timestamp(0) -> timestamp(6)"}},
			want:   []safety.Finding{{Category: modified, Count: 1, Severity: safety.Warning}},
		},
		{
			name:   "an identity that leaves",
			column: difftypes.ColumnDiff{Changes: map[string]string{"identity": "always -> "}},
			want: []safety.Finding{
				{Category: "column_identities_removed", Count: 1, Severity: safety.Destructive},
				{Category: modified, Count: 1, Severity: safety.Warning},
			},
		},
		{
			name:   "an identity that changes generation",
			column: difftypes.ColumnDiff{Changes: map[string]string{"identity": "always -> by default"}},
			want:   []safety.Finding{{Category: modified, Count: 1, Severity: safety.Warning}},
		},
		{
			name:   "an identity that arrives",
			column: difftypes.ColumnDiff{Changes: map[string]string{"identity": " -> always"}},
			want:   []safety.Finding{{Category: modified, Count: 1, Severity: safety.Warning}},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			findings := safety.ClassifySchemaDiff(&difftypes.SchemaDiff{TablesModified: []difftypes.TableDiff{{
				ColumnsModified: []difftypes.ColumnDiff{test.column},
			}}})

			c.Assert(findings, qt.DeepEquals, test.want)
		})
	}
}
