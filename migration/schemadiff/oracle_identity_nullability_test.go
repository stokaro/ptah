package schemadiff_test

import (
	"testing"

	qt "github.com/frankban/quicktest"

	"ptah.run/catalog"
	"ptah.run/core/platform"
	"ptah.run/internal/builtintest"
	"ptah.run/internal/convert/goschematodb"
	"ptah.run/internal/sqlschema"
	"ptah.run/migration/schemadiff"
)

// oracleColumnHeldNotNull compares a one-column table declared as declared
// with the column Oracle holds NOT NULL, and returns the tables the
// comparison modifies.
func oracleColumnHeldNotNull(c *qt.C, declared string) []string {
	c.Helper()
	runtime := builtintest.Runtime()
	desired, _, err := sqlschema.ReadWith(c.Context(), []byte("CREATE TABLE t ("+declared+");"),
		platform.Oracle, nil, sqlschema.Options{Owners: runtime.SQL()})
	c.Assert(err, qt.IsNil)
	current, err := goschematodb.ToDBSchema(c.Context(), &desired, platform.Oracle, runtime)
	c.Assert(err, qt.IsNil)
	c.Assert(current.Tables, qt.HasLen, 1)
	c.Assert(current.Tables[0].Columns, qt.HasLen, 1)
	current.Tables[0].Columns[0].IsNullable = "NO"

	diff, err := schemadiff.CompareWithDatabaseInfo(c.Context(), &desired, current,
		catalog.ServerInfo{Dialect: platform.Oracle}, nil, runtime)
	c.Assert(err, qt.IsNil)
	modified := make([]string, 0, len(diff.TablesModified))
	for _, table := range diff.TablesModified {
		modified = append(modified, table.TableName)
	}
	return modified
}

// Oracle builds every identity column NOT NULL: one declared GENERATED ...
// AS IDENTITY, a serial type and an AUTO_INCREMENT flag, each of which the
// renderer writes as an identity column. A declaration that leaves NOT NULL
// out compares equal to it; compared as declared, the plan writes MODIFY (c
// ... NULL), which Oracle answers with ORA-01451.
func TestCompareOracleIdentity_ImplicitNotNull(t *testing.T) {
	for _, declared := range []string{
		"c NUMBER(10) GENERATED ALWAYS AS IDENTITY",
		"c NUMBER(10) GENERATED BY DEFAULT AS IDENTITY",
		"c SERIAL",
		"c NUMBER(10) AUTO_INCREMENT",
	} {
		t.Run(declared, func(t *testing.T) {
			c := qt.New(t)
			c.Assert(oracleColumnHeldNotNull(c, declared), qt.HasLen, 0)
		})
	}
}

// The control: a plain column declared without NOT NULL and held NOT NULL is
// a change.
func TestCompareOracleIdentity_APlainColumnStaysNullable(t *testing.T) {
	c := qt.New(t)
	c.Assert(oracleColumnHeldNotNull(c, "c NUMBER(10)"), qt.DeepEquals, []string{"t"})
}
