package schemadiff_test

import (
	"testing"

	qt "github.com/frankban/quicktest"

	"ptah.run/catalog"
	"ptah.run/core/platform"
	"ptah.run/internal/builtintest"
	"ptah.run/internal/convert/goschematodb"
	"ptah.run/internal/sqlschema"
	"ptah.run/migration/schemadiff"
)

// oracleIdentityChanges compares a one-column table declared as declared with
// the column Oracle holds NOT NULL under the identity generation held, empty
// for none, and returns the identity change of each column it modifies.
func oracleIdentityChanges(c *qt.C, declared, held string) []string {
	c.Helper()
	runtime := builtintest.Runtime()
	desired, _, err := sqlschema.ReadWith(c.Context(), []byte("CREATE TABLE t ("+declared+");"),
		platform.Oracle, nil, sqlschema.Options{Owners: runtime.SQL()})
	c.Assert(err, qt.IsNil)
	current, err := goschematodb.ToDBSchema(c.Context(), &desired, platform.Oracle, runtime)
	c.Assert(err, qt.IsNil)
	c.Assert(current.Tables, qt.HasLen, 1)
	c.Assert(current.Tables[0].Columns, qt.HasLen, 1)
	current.Tables[0].Columns[0].IsNullable = "NO"
	current.Tables[0].Columns[0].IdentityGeneration = held

	diff, err := schemadiff.CompareWithDatabaseInfo(c.Context(), &desired, current,
		catalog.ServerInfo{Dialect: platform.Oracle}, nil, runtime)
	c.Assert(err, qt.IsNil)
	var changes []string
	for _, table := range diff.TablesModified {
		for _, column := range table.ColumnsModified {
			changes = append(changes, column.Changes["identity"])
		}
	}
	return changes
}

// TestCompareOracleIdentity_ComparesTheGeneration compares the identity a
// declaration builds on Oracle with the generation the column holds. An
// auto-increment flag and a serial type build one generated BY DEFAULT, so
// they differ from a column generated ALWAYS. A plain column differs from an
// identity column, and an identity column from a plain one.
func TestCompareOracleIdentity_ComparesTheGeneration(t *testing.T) {
	tests := []struct {
		declared, held string
		want           []string
	}{
		{declared: "c NUMBER(10) GENERATED ALWAYS AS IDENTITY", held: "BY_DEFAULT", want: []string{"BY_DEFAULT -> ALWAYS"}},
		{declared: "c NUMBER(10) GENERATED BY DEFAULT AS IDENTITY", held: "ALWAYS", want: []string{"ALWAYS -> BY_DEFAULT"}},
		{declared: "c SERIAL", held: "ALWAYS", want: []string{"ALWAYS -> BY_DEFAULT"}},
		{declared: "c NUMBER(10) AUTO_INCREMENT", held: "ALWAYS", want: []string{"ALWAYS -> BY_DEFAULT"}},
		{declared: "c NUMBER(10) NOT NULL", held: "BY_DEFAULT", want: []string{"BY_DEFAULT -> "}},
		{declared: "c NUMBER(10) GENERATED BY DEFAULT AS IDENTITY", held: "", want: []string{" -> BY_DEFAULT"}},
		{declared: "c NUMBER(10) AUTO_INCREMENT", held: "", want: []string{" -> BY_DEFAULT"}},
		{declared: "c NUMBER(10) GENERATED ALWAYS AS IDENTITY", held: "ALWAYS", want: nil},
		{declared: "c NUMBER(10) AUTO_INCREMENT", held: "BY_DEFAULT", want: nil},
		{declared: "c SERIAL", held: "BY_DEFAULT", want: nil},
	}
	for _, test := range tests {
		t.Run(test.declared+" over "+test.held, func(t *testing.T) {
			c := qt.New(t)

			c.Assert(oracleIdentityChanges(c, test.declared, test.held), qt.DeepEquals, test.want)
		})
	}
}
