package schemadiff_test

import (
	"testing"

	qt "github.com/frankban/quicktest"

	"ptah.run/catalog"
	"ptah.run/core/platform"
	"ptah.run/internal/builtintest"
	"ptah.run/internal/convert/goschematodb"
	"ptah.run/internal/sqlschema"
	"ptah.run/migration/schemadiff"
)

// YugabyteDB reports an identity column as NOT NULL even when its declaration
// does not write the clause. Comparing the declaration to that read converges.
func TestCompareYugabyteIdentity_ImplicitNotNull(t *testing.T) {
	c := qt.New(t)
	runtime := builtintest.Runtime()
	declared, _, err := sqlschema.ReadWith(c.Context(),
		[]byte("CREATE TABLE t (c int GENERATED BY DEFAULT AS IDENTITY);"),
		platform.YugabyteDB, nil, sqlschema.Options{Owners: runtime.SQL()})
	c.Assert(err, qt.IsNil)
	c.Assert(declared.Fields, qt.HasLen, 1)
	c.Assert(declared.Fields[0].Nullable, qt.IsFalse)
	current, err := goschematodb.ToDBSchema(c.Context(), &declared, platform.YugabyteDB, runtime)
	c.Assert(err, qt.IsNil)
	c.Assert(current.Tables, qt.HasLen, 1)
	c.Assert(current.Tables[0].Columns, qt.HasLen, 1)
	current.Tables[0].Columns[0].IsNullable = "NO"

	diff, err := schemadiff.CompareWithDatabaseInfo(c.Context(), &declared, current,
		catalog.ServerInfo{Dialect: platform.YugabyteDB}, nil, runtime)
	c.Assert(err, qt.IsNil)
	c.Assert(diff.TablesModified, qt.HasLen, 0)
}
