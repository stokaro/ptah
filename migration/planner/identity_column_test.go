package planner_test

import (
	"strings"
	"testing"

	qt "github.com/frankban/quicktest"
)

// TestIdentityColumn_HappyPath pins the plan for a column whose identity differs from
// its declaration. The comparison read the two as synced, so a column went on numbering
// its rows when the declaration said it does not, and the reverse.
func TestIdentityColumn_HappyPath(t *testing.T) {
	const (
		plain   = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint NOT NULL);`
		byDflt  = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY);`
		always  = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED ALWAYS AS IDENTITY);`
		add     = `ALTER TABLE "parent" ALTER COLUMN "n" ADD GENERATED BY DEFAULT AS IDENTITY`
		seed    = `SELECT setval(pg_get_serial_sequence('"parent"', 'n'), max("n")) FROM "parent" HAVING max("n") >= 1`
		dropped = `ALTER TABLE "parent" ALTER COLUMN "n" DROP IDENTITY`
		notNull = "-- POSTGRES: SET NOT NULL fails if any row of \"parent\" holds NULL in \"n\"; the column declares no default to fill it with.\n" +
			`ALTER TABLE "parent" ALTER COLUMN "n" SET NOT NULL`
	)
	tests := []struct {
		name, dialect, held, desired string
		want                         []string
	}{
		{name: "identity against a plain type", dialect: "postgres", held: byDflt, desired: plain, want: []string{dropped}},
		{name: "a plain type against identity", dialect: "postgres", held: plain, desired: byDflt, want: []string{add, seed}},
		{
			name: "another generation", dialect: "postgres", held: byDflt, desired: always,
			want: []string{`ALTER TABLE "parent" ALTER COLUMN "n" SET GENERATED ALWAYS`},
		},
		{
			name: "a nullable column takes NOT NULL ahead of the identity", dialect: "postgres",
			held:    `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint);`,
			desired: byDflt,
			want:    []string{notNull, add, seed},
		},
		{
			name: "a default leaves ahead of the identity", dialect: "postgres",
			held:    `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint NOT NULL DEFAULT 7);`,
			desired: byDflt,
			want:    []string{`ALTER TABLE "parent" ALTER COLUMN "n" DROP DEFAULT`, add, seed},
		},
		{
			name: "a default arrives after the identity leaves", dialect: "postgres",
			held:    byDflt,
			desired: `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint NOT NULL DEFAULT 7);`,
			want:    []string{dropped, `ALTER TABLE "parent" ALTER COLUMN "n" SET DEFAULT 7`},
		},
		{
			name: "a declared start holds the sequence back", dialect: "postgres",
			held:    plain,
			desired: `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100));`,
			want: []string{
				`ALTER TABLE "parent" ALTER COLUMN "n" ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100)`,
				`SELECT setval(pg_get_serial_sequence('"parent"', 'n'), max("n")) FROM "parent" HAVING max("n") >= 100`,
			},
		},
		{name: "identity against a plain type on CockroachDB", dialect: "cockroachdb", held: byDflt, desired: plain, want: []string{dropped}},
		{
			name: "a nullable column on CockroachDB", dialect: "cockroachdb",
			held:    `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint);`,
			desired: byDflt,
			want:    []string{strings.Replace(notNull, "POSTGRES", "COCKROACHDB", 1), add, seed},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			got := columnKeyPlan(c, test.dialect, test.held, test.desired, "id")

			c.Assert(got, qt.DeepEquals, test.want)
		})
	}
}

// TestIdentityColumn_FailurePath pins the pairs that plan nothing: the two agree, or a
// serial column stands on one side.
func TestIdentityColumn_FailurePath(t *testing.T) {
	const (
		byDflt = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY);`
		serial = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigserial NOT NULL);`
	)
	tests := []struct{ name, held, desired string }{
		{name: "the same generation", held: byDflt, desired: byDflt},
		{name: "identity against serial", held: byDflt, desired: serial},
		{name: "serial against identity", held: serial, desired: byDflt},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			got := columnKeyPlan(c, "postgres", test.held, test.desired, "id")

			c.Assert(got, qt.HasLen, 0)
		})
	}
}
