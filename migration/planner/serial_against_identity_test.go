package planner_test

import (
	"testing"

	qt "github.com/frankban/quicktest"
)

// TestSerialAgainstIdentity_HappyPath pins the plan for a serial column against an
// identity generated ALWAYS, which refuses a value an insert names where a serial column
// takes one. The two read as synced.
func TestSerialAgainstIdentity_HappyPath(t *testing.T) {
	const (
		always = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED ALWAYS AS IDENTITY);`
		serial = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigserial NOT NULL);`
	)
	tests := []struct {
		name, dialect, held, desired string
		want                         []string
	}{
		{
			name: "an always identity against serial", dialect: "postgres", held: always, desired: serial,
			want: []string{
				`ALTER TABLE "parent" ALTER COLUMN "n" DROP IDENTITY`,
				`CREATE SEQUENCE "parent_n_seq" AS bigint`,
				`ALTER TABLE "parent" ALTER COLUMN "n" SET DEFAULT nextval('"parent_n_seq"')`,
				`SELECT setval('"parent_n_seq"', max("n")) FROM "parent" HAVING max("n") >= 1`,
				`ALTER SEQUENCE "parent_n_seq" OWNED BY "parent"."n"`,
			},
		},
		{
			name: "serial against an always identity", dialect: "cockroachdb", held: serial, desired: always,
			want: []string{
				`ALTER TABLE "parent" ALTER COLUMN "n" DROP DEFAULT`,
				`ALTER TABLE "parent" ALTER COLUMN "n" ADD GENERATED ALWAYS AS IDENTITY`,
				`SELECT setval(pg_get_serial_sequence('"parent"', 'n'), max("n")) FROM "parent" HAVING max("n") >= 1`,
			},
		},
		{
			name: "an always identity against serial on CockroachDB", dialect: "cockroachdb", held: always, desired: serial,
			want: []string{
				`ALTER TABLE "parent" ALTER COLUMN "n" DROP IDENTITY`,
				`ALTER TABLE "parent" ALTER COLUMN "n" SET DEFAULT unique_rowid()`,
			},
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			got := columnKeyPlan(c, test.dialect, test.held, test.desired, "id")

			c.Assert(got, qt.DeepEquals, test.want)
		})
	}
}

// TestSerialAgainstIdentity_FailurePath pins the pairs that compare equal: a serial column
// and an identity generated BY DEFAULT each take a value an insert names.
func TestSerialAgainstIdentity_FailurePath(t *testing.T) {
	const (
		byDefault = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY);`
		serial    = `CREATE TABLE parent (id bigint PRIMARY KEY, n bigserial NOT NULL);`
	)
	tests := []struct{ name, dialect, held, desired string }{
		{name: "identity against serial", dialect: "postgres", held: byDefault, desired: serial},
		{name: "serial against identity", dialect: "postgres", held: serial, desired: byDefault},
		{name: "identity against serial on CockroachDB", dialect: "cockroachdb", held: byDefault, desired: serial},
		{name: "serial against identity on CockroachDB", dialect: "cockroachdb", held: serial, desired: byDefault},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			got := columnKeyPlan(c, test.dialect, test.held, test.desired, "id")

			c.Assert(got, qt.HasLen, 0)
		})
	}
}
