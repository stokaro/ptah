// objectsNamed is the names of database's objects of kind: tables,
// sequences, or indexes.
func objectsNamed(database schemamodel.Database, kind string) []string {
	var names []string
	switch kind {
	case "table":
		for _, table := range database.Tables {
			names = append(names, table.QualifiedName())
		}
	case "sequence":
		for _, sequence := range database.Sequences {
			names = append(names, sequence.Name)
		}
	default:
		for _, index := range database.Indexes {
			names = append(names, index.Name)
		}
	}
	return names
}

// countOf is how many of names are name.
func countOf(names []string, name string) int {
	return len(slices.DeleteFunc(slices.Clone(names), func(held string) bool { return held != name }))
}

// TestReadGuarded_SkipsWhatTheServerFinds holds a guarded statement whose name
// the server already holds, measured on PostgreSQL 15.19 and 18.6, which the
// server skips with "already exists, skipping": it adds no object. Each row
// is a name the server derives or keeps, and the last statement of each file
// is the guarded one.
func TestReadGuarded_SkipsWhatTheServerFinds(t *testing.T) {
	tests := []struct {
		name   string
		sql    string
		kind   string
		object string
	}{
		{name: "a serial column's sequence", sql: "CREATE TABLE t (id serial, b int);\nCREATE SEQUENCE IF NOT EXISTS t_id_seq START 100;", kind: "sequence", object: "t_id_seq"},
		{name: "an identity column's sequence", sql: "CREATE TABLE t (id int GENERATED BY DEFAULT AS IDENTITY, b int);\nCREATE SEQUENCE IF NOT EXISTS t_id_seq START 100;", kind: "sequence", object: "t_id_seq"},
		{name: "an identity column's named sequence", sql: "CREATE TABLE t (id int GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME myseq), b int);\nCREATE SEQUENCE IF NOT EXISTS myseq START 100;", kind: "sequence", object: "myseq"},
		{name: "a column's primary key", sql: "CREATE TABLE t (id int PRIMARY KEY, b int);\nCREATE INDEX IF NOT EXISTS t_pkey ON t (b);", kind: "index", object: "t_pkey"},
		{name: "a column's unique key", sql: "CREATE TABLE t (a int UNIQUE, b int);\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);", kind: "index", object: "t_a_key"},
		{name: "an unnamed table primary key", sql: "CREATE TABLE t (a int, b int, PRIMARY KEY (a, b));\nCREATE INDEX IF NOT EXISTS t_pkey ON t (b);", kind: "index", object: "t_pkey"},
		{name: "an unnamed table unique key", sql: "CREATE TABLE t (a int, b int, c int, UNIQUE (a, b));\nCREATE INDEX IF NOT EXISTS t_a_b_key ON t (c);", kind: "index", object: "t_a_b_key"},
		{name: "a primary key past a check of its name on another table", sql: "CREATE TABLE u (a int, CONSTRAINT t_pkey CHECK (a > 0));\nCREATE TABLE t (id int PRIMARY KEY, b int);\nCREATE INDEX IF NOT EXISTS t_pkey1 ON t (b);", kind: "index", object: "t_pkey1"},
		{name: "an unnamed key past a named key of other columns", sql: "CREATE TABLE t (a int, b int, CONSTRAINT k UNIQUE (b), UNIQUE (a));\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);", kind: "index", object: "t_a_key"},
		{name: "a primary key named by an equal unique key", sql: "CREATE TABLE t (id int PRIMARY KEY, b int, CONSTRAINT k UNIQUE (id));\nCREATE INDEX IF NOT EXISTS k ON t (b);", kind: "index", object: "k"},
		{name: "two keys ALTER TABLE adds apart", sql: "CREATE TABLE t (a int, b int);\nALTER TABLE t ADD UNIQUE (a), ADD UNIQUE (a);\nCREATE INDEX IF NOT EXISTS t_a_key1 ON t (b);", kind: "index", object: "t_a_key1"},
		{name: "a column's key and an equal key ALTER TABLE adds", sql: "CREATE TABLE t (a int, b int);\nALTER TABLE t ADD COLUMN c int UNIQUE, ADD UNIQUE (c);\nCREATE INDEX IF NOT EXISTS t_c_key1 ON t (a);", kind: "index", object: "t_c_key1"},
		{name: "a deferrable key beside an equal one", sql: "CREATE TABLE t (a int, b int, UNIQUE (a) DEFERRABLE, UNIQUE (a));\nCREATE INDEX IF NOT EXISTS t_a_key1 ON t (b);", kind: "index", object: "t_a_key1"},
		{name: "a key with INCLUDE beside one without", sql: "CREATE TABLE t (a int, b int, UNIQUE (a) INCLUDE (b), UNIQUE (a));\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);", kind: "index", object: "t_a_key"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			database := readGuarded(c, test.sql)

			c.Assert(countOf(objectsNamed(database, test.kind), test.object), qt.Equals, 0)
		})
	}
}

// TestReadGuarded_SkipsASequenceADroppedTableDrewFrom holds that DROP TABLE
// keeps a sequence the table's default drew from: the table does not own it,
// so PostgreSQL 15.19 and 18.6 keep it, and a later CREATE SEQUENCE IF NOT
// EXISTS of it is skipped and leaves its start.
func TestReadGuarded_SkipsASequenceADroppedTableDrewFrom(t *testing.T) {
	c := qt.New(t)

	database := readGuarded(c, "CREATE SEQUENCE s START 5;\nCREATE TABLE t (id int DEFAULT nextval('s'), a int);\n"+
		"DROP TABLE t;\nCREATE SEQUENCE IF NOT EXISTS s START 10;")

	c.Assert(database.Sequences, qt.HasLen, 1)
	c.Assert(*database.Sequences[0].Start, qt.Equals, int64(5))
}

// TestReadGuarded_RunsWhatTheServerRuns holds a guarded statement whose name
// the server does not hold, measured on PostgreSQL 15.19 and 18.6, so it runs:
// a name a DROP TABLE or DROP COLUMN removed, a key the server folds into
// another, or a name it gives another key. The reader keeps the object; a
// reader that skipped it would plan to drop it from the database the file
// built.
func TestReadGuarded_RunsWhatTheServerRuns(t *testing.T) {
	tests := []struct {
		name   string
		sql    string
		kind   string
		object string
	}{
		{name: "an index of a table dropped and created again", sql: "CREATE TABLE t (a int);\nCREATE INDEX i ON t (a);\nDROP TABLE t;\nCREATE TABLE t (a int);\nCREATE INDEX IF NOT EXISTS i ON t (a);", kind: "index", object: "i"},
		{name: "the primary key of a dropped table", sql: "CREATE TABLE t (id int PRIMARY KEY);\nDROP TABLE t;\nCREATE TABLE t (id int, b int);\nCREATE INDEX IF NOT EXISTS t_pkey ON t (b);", kind: "index", object: "t_pkey"},
		{name: "the serial sequence of a dropped table", sql: "CREATE TABLE t (id serial, a int);\nDROP TABLE t;\nCREATE SEQUENCE IF NOT EXISTS t_id_seq START 100;", kind: "sequence", object: "t_id_seq"},
		{name: "the serial sequence of a dropped column", sql: "CREATE TABLE t (id serial, a int);\nALTER TABLE t DROP COLUMN id;\nCREATE SEQUENCE IF NOT EXISTS t_id_seq START 100;", kind: "sequence", object: "t_id_seq"},
		{name: "the unique key of a dropped column", sql: "CREATE TABLE t (a int UNIQUE, b int);\nALTER TABLE t DROP COLUMN a;\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);", kind: "index", object: "t_a_key"},
		{name: "the unique key of a renamed column dropped", sql: "CREATE TABLE t (a int UNIQUE, b int);\nALTER TABLE t RENAME COLUMN a TO c;\nALTER TABLE t DROP COLUMN c;\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);", kind: "index", object: "t_a_key"},
		{name: "the unique key a primary key on the same column folds", sql: "CREATE TABLE t (id int PRIMARY KEY UNIQUE, b int);\nCREATE INDEX IF NOT EXISTS t_id_key ON t (b);", kind: "index", object: "t_id_key"},
		{name: "a table unique key an equal primary key folds", sql: "CREATE TABLE t (id int PRIMARY KEY, b int, UNIQUE (id));\nCREATE INDEX IF NOT EXISTS t_id_key ON t (b);", kind: "index", object: "t_id_key"},
		{name: "a table unique key written before an equal primary key", sql: "CREATE TABLE t (a int, b int, UNIQUE (a), PRIMARY KEY (a));\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);", kind: "index", object: "t_a_key"},
		{name: "the second of two equal unnamed keys", sql: "CREATE TABLE t (a int UNIQUE, b int, UNIQUE (a));\nCREATE INDEX IF NOT EXISTS t_a_key1 ON t (b);", kind: "index", object: "t_a_key1"},
		{name: "the primary key name an equal named unique key takes", sql: "CREATE TABLE t (id int PRIMARY KEY, b int, CONSTRAINT k UNIQUE (id));\nCREATE INDEX IF NOT EXISTS t_pkey ON t (b);", kind: "index", object: "t_pkey"},
		{name: "the second of two equal named keys", sql: "CREATE TABLE t (a int, b int, CONSTRAINT k1 UNIQUE (a), CONSTRAINT k2 UNIQUE (a));\nCREATE INDEX IF NOT EXISTS k2 ON t (b);", kind: "index", object: "k2"},
		{name: "a column key named by an equal named key", sql: "CREATE TABLE t (a int UNIQUE, b int, CONSTRAINT k UNIQUE (a));\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);", kind: "index", object: "t_a_key"},
		{name: "the unique key of an added primary key column", sql: "CREATE TABLE t (a int);\nALTER TABLE t ADD COLUMN id int PRIMARY KEY UNIQUE;\nCREATE INDEX IF NOT EXISTS t_id_key ON t (a);", kind: "index", object: "t_id_key"},
		{name: "the sequence an identity column names otherwise", sql: "CREATE TABLE t (id int GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME myseq), b int);\nCREATE SEQUENCE IF NOT EXISTS t_id_seq START 100;", kind: "sequence", object: "t_id_seq"},
		{name: "the key of the first of two long columns, dropped", sql: "CREATE TABLE t (\"ccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc1\" int UNIQUE, \"ccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc2\" int UNIQUE, b int);\nALTER TABLE t DROP COLUMN \"ccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc1\";\nCREATE INDEX IF NOT EXISTS t_ccccccccccccccccccccccccccccccccccccccccccccccccccccccccc_key ON t (b);", kind: "index", object: "t_ccccccccccccccccccccccccccccccccccccccccccccccccccccccccc_key"},
		{name: "a table of a name written in capitals", sql: "CREATE TABLE t (a int);\nCREATE TABLE IF NOT EXISTS \"T\" (b int);", kind: "table", object: "T"},
		{name: "a table in another schema", sql: "CREATE SCHEMA s;\nCREATE TABLE s.t (a int);\nCREATE TABLE IF NOT EXISTS t (a int, b int);", kind: "table", object: "t"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			database := readGuarded(c, test.sql)

			c.Assert(countOf(objectsNamed(database, test.kind), test.object), qt.Equals, 1)
		})
	}
}

// readAfter reads earlier as one file and then later as the next one, as a
// load reads a schema directory's files or two --to sources, and returns what
// later declares and the model it read onto.
func readAfter(c *qt.C, dialect, earlier, later string) (declared, onto schemamodel.Database) {
	c.Helper()
	first, _, err := sqlschema.ReadOnto([]byte(earlier), dialect, sqlschema.NewDocument(&schemamodel.Database{}))
	c.Assert(err, qt.IsNil)
	declared, _, err = sqlschema.ReadOnto([]byte(later), dialect, sqlschema.NewDocument(&first))
	c.Assert(err, qt.IsNil)
	return declared, first
}

// TestReadOnto_SkipsWhatAnEarlierFileHolds holds that a guarded statement of a
// later file is skipped when an earlier file holds its name, as the server
// runs the files in order: an index, a key's index, a sequence written with
// its schema and then without it. The later file is read onto the earlier
// file's model, so the names come from that model.
func TestReadOnto_SkipsWhatAnEarlierFileHolds(t *testing.T) {
	tests := []struct {
		name    string
		dialect string
		earlier string
		later   string
		kind    string
	}{
		{name: "an index", dialect: platform.Postgres, earlier: "CREATE TABLE t (a int, b int);\nCREATE INDEX i ON t (a);", later: "CREATE INDEX IF NOT EXISTS i ON t (b);", kind: "index"},
		{name: "a primary key's index", dialect: platform.Postgres, earlier: "CREATE TABLE t (id int PRIMARY KEY, b int);", later: "CREATE INDEX IF NOT EXISTS t_pkey ON t (b);", kind: "index"},
		{name: "a named key's index", dialect: platform.Postgres, earlier: "CREATE TABLE t (a int, b int, CONSTRAINT k UNIQUE (a));", later: "CREATE INDEX IF NOT EXISTS k ON t (b);", kind: "index"},
		{name: "a named primary key's index", dialect: platform.Postgres, earlier: "CREATE TABLE t (a int, b int, CONSTRAINT p PRIMARY KEY (a));", later: "CREATE INDEX IF NOT EXISTS p ON t (b);", kind: "index"},
		{name: "a CockroachDB sequence", dialect: platform.CockroachDB, earlier: "CREATE SEQUENCE s START 5;", later: "CREATE SEQUENCE IF NOT EXISTS s START 10;", kind: "sequence"},
		{name: "a CockroachDB sequence written with its schema", dialect: platform.CockroachDB, earlier: "CREATE SEQUENCE public.s START 5;", later: "CREATE SEQUENCE IF NOT EXISTS s START 10;", kind: "sequence"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			declared, _ := readAfter(c, test.dialect, test.earlier, test.later)

			c.Assert(objectsNamed(declared, test.kind), qt.HasLen, 0)
		})
	}
}

// TestReadOnto_RunsWhatAnEarlierFileNoLongerHolds holds that a later file's
// DROP TABLE removes the names the earlier file's table owned, so a guarded
// statement of the name runs, as on the server.
func TestReadOnto_RunsWhatAnEarlierFileNoLongerHolds(t *testing.T) {
	tests := []struct {
		name    string
		earlier string
		later   string
		object  string
	}{
		{name: "an index", earlier: "CREATE TABLE t (a int);\nCREATE INDEX i ON t (a);", later: "DROP TABLE t;\nCREATE TABLE t (a int);\nCREATE INDEX IF NOT EXISTS i ON t (a);", object: "i"},
		{name: "a primary key's index", earlier: "CREATE TABLE t (id int PRIMARY KEY);", later: "DROP TABLE t;\nCREATE TABLE t (id int, b int);\nCREATE INDEX IF NOT EXISTS t_pkey ON t (b);", object: "t_pkey"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			declared, _ := readAfter(c, platform.Postgres, test.earlier, test.later)

			c.Assert(objectsNamed(declared, "index"), qt.DeepEquals, []string{test.object})
		})
	}
}

// TestReadGuarded_ReplacesARoutineByNameWithoutOverloading holds that a server
// that holds one routine per name replaces it whatever arguments the
// replacement takes: MariaDB 11.8.9 and 12.3.3 take `CREATE OR REPLACE
// FUNCTION f(a int)` in the place of `f()`, and so does SQL Server's CREATE OR
// ALTER. MariaDB drops the routine's comment, so the replacement's comment is
// what stays.
func TestReadGuarded_ReplacesARoutineByNameWithoutOverloading(t *testing.T) {
	tests := []struct {
		name    string
		dialect string
		sql     string
		want    string
		comment string
	}{
		{
			name: "MariaDB", dialect: platform.MariaDB,
			sql:  "CREATE FUNCTION f() RETURNS int COMMENT 'old' RETURN 1;\nCREATE OR REPLACE FUNCTION f(a int) RETURNS int RETURN a;",
			want: "a int",
		},
		{
			name: "SQL Server", dialect: platform.SQLServer,
			sql: "CREATE FUNCTION dbo.f() RETURNS int AS BEGIN RETURN 1; END;\nGO\n" +
				"CREATE OR ALTER FUNCTION dbo.f(@a int) RETURNS int AS BEGIN RETURN @a; END;",
			want: "@a int",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			database, _, err := sqlschema.ReadWith(context.Background(), []byte(test.sql), test.dialect, nil, sqlschema.Options{Owners: sqlext.None()})

			c.Assert(err, qt.IsNil)
			c.Assert(database.Functions, qt.HasLen, 1)
			c.Assert(database.Functions[0].Parameters, qt.Equals, test.want)
			c.Assert(database.Functions[0].Comment, qt.Equals, test.comment)
		})
	}
}

// TestReadGuarded_KeepsAnIndexADropColumnLeaves holds that a DROP COLUMN of
// another column leaves an index in place, as PostgreSQL 15.19 and 18.6 keep
// it, so a guarded CREATE INDEX of its name is skipped and the first
// definition stands.
func TestReadGuarded_KeepsAnIndexADropColumnLeaves(t *testing.T) {
	c := qt.New(t)

	database := readGuarded(c, "CREATE TABLE t (a int, b int, c int);\nCREATE INDEX i ON t (a);\n"+
		"ALTER TABLE t DROP COLUMN b;\nCREATE INDEX IF NOT EXISTS i ON t (c);")

	c.Assert(database.Indexes, qt.HasLen, 1)
	c.Assert(database.Indexes[0].Fields, qt.DeepEquals, []string{"a"})
}

// TestReadOnto_RunsATableAnEarlierFileHadDropped holds that a later file that
// drops a table an earlier file created, and creates it again under IF NOT
// EXISTS, declares the new table, as the server runs both statements.
func TestReadOnto_RunsATableAnEarlierFileHadDropped(t *testing.T) {
	c := qt.New(t)

	declared, _ := readAfter(c, platform.Postgres, "CREATE TABLE t (a int);", "DROP TABLE t;\nCREATE TABLE IF NOT EXISTS t (a int, b int);")

	c.Assert(objectsNamed(declared, "table"), qt.DeepEquals, []string{"t"})
	c.Assert(columnsOfTable(declared, "T"), qt.DeepEquals, []string{"a", "b"})
}
