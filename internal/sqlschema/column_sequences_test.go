// readModel reads sql as a PostgreSQL schema file.
func readModel(c *qt.C, dialect, sql string) schemamodel.Database {
	c.Helper()
	database, _, err := sqlschema.Read([]byte(sql), dialect)
	c.Assert(err, qt.IsNil)
	return database
}

// The statements pg_dump writes for a serial or an identity column read as
// the model the column's one-statement spelling reads as: a serial column
// with no sequence of its own, and an identity column with its options as
// written. A dump of a database therefore declares what a read of that
// database reports, and a plan from it creates no sequence the database holds.
func TestRead_PgDumpColumnSequences_HappyPath(t *testing.T) {
	for _, test := range []struct {
		name, dump, written string
	}{
		{
			name: "serial",
			dump: `CREATE TABLE public.s_int (
    id integer NOT NULL,
    name text
);
CREATE SEQUENCE public.s_int_id_seq
    AS integer
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;
ALTER SEQUENCE public.s_int_id_seq OWNED BY public.s_int.id;
ALTER TABLE ONLY public.s_int ALTER COLUMN id SET DEFAULT nextval('public.s_int_id_seq'::regclass);
ALTER TABLE ONLY public.s_int
    ADD CONSTRAINT s_int_pkey PRIMARY KEY (id);`,
			written: `CREATE TABLE public.s_int (id serial NOT NULL, name text);
ALTER TABLE ONLY public.s_int ADD CONSTRAINT s_int_pkey PRIMARY KEY (id);`,
		},
		{
			name: "bigserial, whose sequence states no type",
			dump: `CREATE TABLE public.s_big (id bigint NOT NULL);
CREATE SEQUENCE public.s_big_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE public.s_big_id_seq OWNED BY public.s_big.id;
ALTER TABLE ONLY public.s_big ALTER COLUMN id SET DEFAULT nextval('public.s_big_id_seq'::regclass);`,
			written: `CREATE TABLE public.s_big (id bigserial NOT NULL);`,
		},
		{
			name: "smallserial",
			dump: `CREATE TABLE public.s_small (id smallint NOT NULL);
CREATE SEQUENCE public.s_small_id_seq AS smallint START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE public.s_small_id_seq OWNED BY public.s_small.id;
ALTER TABLE ONLY public.s_small ALTER COLUMN id SET DEFAULT nextval('public.s_small_id_seq'::regclass);`,
			written: `CREATE TABLE public.s_small (id smallserial NOT NULL);`,
		},
		{
			name: "quoted names",
			dump: `CREATE TABLE public."Order" ("Id" bigint NOT NULL);
CREATE SEQUENCE public."Order_Id_seq" START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE public."Order_Id_seq" OWNED BY public."Order"."Id";
ALTER TABLE ONLY public."Order" ALTER COLUMN "Id" SET DEFAULT nextval('public."Order_Id_seq"'::regclass);`,
			written: `CREATE TABLE public."Order" ("Id" bigserial NOT NULL);`,
		},
		{
			name: "a schema other than the default",
			dump: `CREATE SCHEMA app;
CREATE TABLE app.s_other (id integer NOT NULL);
CREATE SEQUENCE app.s_other_id_seq AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE app.s_other_id_seq OWNED BY app.s_other.id;
ALTER TABLE ONLY app.s_other ALTER COLUMN id SET DEFAULT nextval('app.s_other_id_seq'::regclass);`,
			written: `CREATE SCHEMA app;
CREATE TABLE app.s_other (id serial NOT NULL);`,
		},
		{
			name: "unqualified names, no cast, the default first and the owner in CREATE SEQUENCE",
			dump: `CREATE TABLE t (id bigint NOT NULL);
ALTER TABLE t ALTER COLUMN id SET DEFAULT nextval('t_id_seq');
CREATE SEQUENCE t_id_seq OWNED BY t.id;`,
			written: `CREATE TABLE t (id bigserial NOT NULL);`,
		},
		{
			name: "a primary key column with no NOT NULL",
			dump: `CREATE TABLE t (id integer PRIMARY KEY);
CREATE SEQUENCE t_id_seq AS integer;
ALTER SEQUENCE t_id_seq OWNED BY t.id;
ALTER TABLE t ALTER COLUMN id SET DEFAULT nextval('t_id_seq'::regclass);`,
			written: `CREATE TABLE t (id serial PRIMARY KEY);`,
		},
		{
			name: "identity generated always",
			dump: `CREATE TABLE public.i_always (id integer NOT NULL, v text);
ALTER TABLE public.i_always ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (
    SEQUENCE NAME public.i_always_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);`,
			written: `CREATE TABLE public.i_always (id integer GENERATED ALWAYS AS IDENTITY (
    SEQUENCE NAME public.i_always_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
) NOT NULL, v text);`,
		},
		{
			name: "identity generated by default, with options",
			dump: `CREATE TABLE public.i_opts (id bigint NOT NULL);
ALTER TABLE public.i_opts ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5 CACHE 10);
ALTER TABLE ONLY public.i_opts ADD CONSTRAINT i_opts_pkey PRIMARY KEY (id);`,
			written: `CREATE TABLE public.i_opts (id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5 CACHE 10) NOT NULL);
ALTER TABLE ONLY public.i_opts ADD CONSTRAINT i_opts_pkey PRIMARY KEY (id);`,
		},
		{
			name: "identity on a primary key column with no NOT NULL",
			dump: `CREATE TABLE t (id bigint PRIMARY KEY);
ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;`,
			written: `CREATE TABLE t (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);`,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			dumped := readModel(c, platform.Postgres, test.dump)

			c.Assert(dumped, qt.DeepEquals, readModel(c, platform.Postgres, test.written))
		})
	}
}

// A sequence a column owns stays a sequence of its own, with its owner and
// its options, wherever the serial type would not build it as the file states
// it: what the file states is kept rather than dropped. The column keeps the
// type and the default it was given.
func TestRead_OwnedSequenceKept_HappyPath(t *testing.T) {
	const table = "CREATE TABLE t (id integer NOT NULL);\n"
	const drawn = "ALTER TABLE t ALTER COLUMN id SET DEFAULT nextval('t_id_seq'::regclass);\n"
	const owned = "ALTER SEQUENCE t_id_seq OWNED BY t.id;\n"
	for _, test := range []struct {
		name, sql                string
		wantOwnedBy, wantDefault string
		wantNullable             bool
	}{
		{
			name:        "an increment the serial type does not give",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer INCREMENT BY 10;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a start the serial type does not give",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer START WITH 5;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a minimum the serial type does not give",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer MINVALUE 0;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a cache the serial type does not give",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer CACHE 20;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a maximum below the type's",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer MAXVALUE 1000;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a cycle",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer CYCLE;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a type that is not the column's",
			sql:         table + "CREATE SEQUENCE t_id_seq;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a comment",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer;\n" + owned + drawn + "COMMENT ON SEQUENCE t_id_seq IS 'ids';\n",
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			// The serial type names the sequence of t.key t_key_seq.
			name: "a name the serial type does not give",
			sql: "CREATE TABLE t (key integer NOT NULL);\nCREATE SEQUENCE t_id_seq AS integer;\n" +
				"ALTER SEQUENCE t_id_seq OWNED BY t.key;\nALTER TABLE t ALTER COLUMN key SET DEFAULT nextval('t_id_seq'::regclass);\n",
			wantOwnedBy: "t.key", wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "a nullable column",
			sql:         "CREATE TABLE t (id integer);\nCREATE SEQUENCE t_id_seq AS integer;\n" + owned + drawn,
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::regclass)", wantNullable: true,
		},
		{
			name:        "a name looked up on each call",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer;\n" + owned + "ALTER TABLE t ALTER COLUMN id SET DEFAULT nextval('t_id_seq'::text);\n",
			wantOwnedBy: "t.id", wantDefault: "nextval('t_id_seq'::text)",
		},
		{
			name:        "no default",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer;\n" + owned,
			wantOwnedBy: "t.id",
		},
		{
			name:        "no owner",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer;\n" + drawn,
			wantDefault: "nextval('t_id_seq'::regclass)",
		},
		{
			name:        "the owner taken away",
			sql:         table + "CREATE SEQUENCE t_id_seq AS integer OWNED BY t.id;\n" + drawn + "ALTER SEQUENCE t_id_seq OWNED BY NONE;\n",
			wantDefault: "nextval('t_id_seq'::regclass)",
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			database := readModel(c, platform.Postgres, test.sql)

			c.Assert(database.Sequences, qt.HasLen, 1)
			c.Assert(database.Sequences[0].Name, qt.Equals, "t_id_seq")
			c.Assert(database.Sequences[0].OwnedBy, qt.Equals, test.wantOwnedBy)
			c.Assert(database.Fields, qt.HasLen, 1)
			c.Assert(database.Fields[0].Type, qt.Equals, "integer")
			c.Assert(database.Fields[0].DefaultExpr, qt.Equals, test.wantDefault)
			c.Assert(database.Fields[0].Nullable, qt.Equals, test.wantNullable)
		})
	}
}

// A schema directory is read as one script: a sequence an earlier file
// declares is owned by a statement of a later one, and folds into its column
// there.
func TestReadOnto_OwnedSequenceOfAnEarlierFile_HappyPath(t *testing.T) {
	c := qt.New(t)
	earlier := readModel(c, platform.Postgres, "CREATE TABLE t (id integer NOT NULL);\nCREATE SEQUENCE t_id_seq AS integer;")

	_, _, err := sqlschema.ReadOnto([]byte(
		"ALTER SEQUENCE t_id_seq OWNED BY t.id;\n"+
			"ALTER TABLE t ALTER COLUMN id SET DEFAULT nextval('t_id_seq'::regclass);",
	), platform.Postgres, sqlschema.NewDocument(&earlier))

	c.Assert(err, qt.IsNil)
	c.Assert(earlier.Sequences, qt.IsNil)
	c.Assert(earlier.Fields[0].Type, qt.Equals, "serial")
	c.Assert(earlier.Fields[0].DefaultExpr, qt.Equals, "")
}

// The fold runs only where the descriptor says a serial column draws from a
// sequence it owns (Comparison.SerialOwnsSequence), which is PostgreSQL alone.
// On CockroachDB and YugabyteDB the statements keep the sequence and its owner.
func TestRead_OwnedSequenceOtherDialects_HappyPath(t *testing.T) {
	const dump = `CREATE TABLE s_int (id integer NOT NULL);
CREATE SEQUENCE s_int_id_seq AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE s_int_id_seq OWNED BY s_int.id;
ALTER TABLE ONLY s_int ALTER COLUMN id SET DEFAULT nextval('s_int_id_seq'::regclass);`
	for _, dialect := range []string{platform.CockroachDB, platform.YugabyteDB} {
		t.Run(dialect, func(t *testing.T) {
			c := qt.New(t)

			database := readModel(c, dialect, dump)

			c.Assert(database.Sequences, qt.HasLen, 1)
			c.Assert(database.Sequences[0].OwnedBy, qt.Equals, "s_int.id")
			c.Assert(database.Fields[0].Type, qt.Equals, "integer")
			c.Assert(database.Fields[0].DefaultExpr, qt.Equals, "nextval('s_int_id_seq'::regclass)")
		})
	}
}

// OWNED BY that names something the schema does not declare, or a column the
// server would not let own the sequence, is refused.
func TestRead_AlterSequenceOwnedBy_FailurePath(t *testing.T) {
	const table = "CREATE SCHEMA app;\nCREATE TABLE t (id integer NOT NULL);\n"
	for _, test := range []struct {
		name, sql, wantErr string
	}{
		{
			name:    "a sequence the schema does not declare",
			sql:     table + "ALTER SEQUENCE s OWNED BY t.id;",
			wantErr: `.*ALTER SEQUENCE s names a sequence this schema does not declare.*`,
		},
		{
			name:    "a table the schema does not declare",
			sql:     table + "CREATE SEQUENCE s;\nALTER SEQUENCE s OWNED BY other.id;",
			wantErr: `.*ALTER SEQUENCE s OWNED BY other.id names a table this schema does not declare.*`,
		},
		{
			name:    "a column the table does not declare",
			sql:     table + "CREATE SEQUENCE s;\nALTER SEQUENCE s OWNED BY t.other;",
			wantErr: `.*ALTER SEQUENCE s OWNED BY t.other names a column the table does not declare`,
		},
		{
			name:    "a column with no table",
			sql:     table + "CREATE SEQUENCE s;\nALTER SEQUENCE s OWNED BY id;",
			wantErr: `.*ALTER SEQUENCE s OWNED BY id: OWNED BY names a column of a table, or NONE`,
		},
		{
			name:    "a table in another schema",
			sql:     table + "CREATE SEQUENCE app.s;\nALTER SEQUENCE app.s OWNED BY t.id;",
			wantErr: `.*ALTER SEQUENCE app.s OWNED BY t.id: a sequence is owned by a column of a table in its own schema`,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			database, _, err := sqlschema.Read([]byte(test.sql), platform.Postgres)

			c.Assert(err, qt.ErrorMatches, test.wantErr)
			c.Assert(database, qt.DeepEquals, schemamodel.Database{})
		})
	}
}

// sequenceScript is an owner whose grammar parses every document into the
// statements it holds, and converts none of them itself.
type sequenceScript struct{ statements []ast.Node }

func (s sequenceScript) Parse(context.Context, sqlext.SourceFile) (*ast.StatementList, error) {
	return &ast.StatementList{Statements: s.statements}, nil
}

func (sequenceScript) Statement(sqlschema.Scope, ast.Node) (bool, error) { return false, nil }

func (sequenceScript) AlterOperation(sqlschema.Scope, sqlschema.Table, *ast.ExtensionAlterOperation) (bool, error) {
	return false, nil
}

// ALTER SEQUENCE carries an owner and nothing else: a statement whose parser
// read an option into it is refused, because the option is the sequence's
// declaration and belongs in its CREATE SEQUENCE.
func TestConvertScript_AlterSequenceOptions_FailurePath(t *testing.T) {
	c := qt.New(t)
	request := sqlext.GrammarRequest{Target: platform.Postgres, Files: []sqlext.SourceFile{{Path: "a.sql", Text: "sequence"}}}
	script := sequenceScript{statements: []ast.Node{
		ast.NewCreateTable("t").AddColumn(ast.NewColumn("id", "bigint")),
		ast.NewCreateSequence("s"),
		ast.NewAlterSequence("s").SetIncrement(5).SetOwnedBy("t.id"),
	}}

	result, err := sqlschema.ConvertScript(t.Context(), request, script)

	c.Assert(err, qt.ErrorMatches, `a.sql: .*ALTER SEQUENCE s: a schema file may set a sequence's owner this way; declare its options in its CREATE SEQUENCE`)
	c.Assert(err, qt.ErrorIs, sqlschema.ErrUnmodeledStatement)
	c.Assert(result, qt.DeepEquals, sqlext.GrammarResult{})
}

// ADD GENERATED is refused on a column the server refuses it on, with the
// server's reason.
func TestRead_AlterColumnAddIdentity_FailurePath(t *testing.T) {
	for _, test := range []struct {
		name, sql, wantErr string
	}{
		{
			name:    "an identity column",
			sql:     "CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY);\nALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 2, column 1: ALTER TABLE t ALTER COLUMN id ADD GENERATED: the column is an identity column already`,
		},
		{
			name:    "a serial column",
			sql:     "CREATE TABLE t (id serial);\nALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 2, column 1: ALTER TABLE t ALTER COLUMN id ADD GENERATED: the column has a default, and an identity column takes none`,
		},
		{
			name:    "a column with a default",
			sql:     "CREATE TABLE t (id bigint NOT NULL DEFAULT 7);\nALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 2, column 1: ALTER TABLE t ALTER COLUMN id ADD GENERATED: the column has a default, and an identity column takes none`,
		},
		{
			name:    "a nullable column",
			sql:     "CREATE TABLE t (id bigint);\nALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 2, column 1: ALTER TABLE t ALTER COLUMN id ADD GENERATED: the column has to be NOT NULL to take an identity`,
		},
		{
			name:    "a type that is not an integer",
			sql:     "CREATE TABLE t (id numeric NOT NULL);\nALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 2, column 1: ALTER TABLE t ALTER COLUMN id ADD GENERATED: an identity column is smallint, integer or bigint`,
		},
		{
			// The identity takes t_id_seq, so the server refuses a second
			// relation of that name.
			name:    "a sequence of the identity's name declared after it",
			sql:     "CREATE TABLE t (id bigint NOT NULL);\nALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;\nCREATE SEQUENCE t_id_seq;",
			wantErr: `a name the file declares is already in use: sequence "t_id_seq" in schema "public" takes the name of sequence "t_id_seq", and the server refuses the second declaration`,
		},
		{
			name:    "a column the table does not declare",
			sql:     "CREATE TABLE t (id bigint NOT NULL);\nALTER TABLE t ALTER COLUMN other ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 2, column 1: ALTER TABLE t ALTER COLUMN other names a column the table does not declare`,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			database, _, err := sqlschema.Read([]byte(test.sql), platform.Postgres)

			c.Assert(err, qt.ErrorMatches, test.wantErr)
			c.Assert(database, qt.DeepEquals, schemamodel.Database{})
		})
	}
}
