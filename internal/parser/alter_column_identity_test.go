// ALTER COLUMN ... ADD GENERATED ... AS IDENTITY, which pg_dump writes for
// every identity column, reads into the identity the same clause gives a
// column definition: the generation, and the options as written. A start or
// an increment written alone is read into its field, as on a column.
func TestParse_AlterColumnAddIdentity_HappyPath(t *testing.T) {
	for _, test := range []struct {
		name, dialect, sql string
		want               *ast.AlterColumnOperation
	}{
		{
			name: "ALWAYS", dialect: "postgres",
			sql:  "ALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			want: &ast.AlterColumnOperation{ColumnName: "id", Action: ast.AlterColumnAddIdentity, IdentityGeneration: "ALWAYS"},
		},
		{
			name: "BY DEFAULT", dialect: "postgres",
			sql:  "ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;",
			want: &ast.AlterColumnOperation{ColumnName: "id", Action: ast.AlterColumnAddIdentity, IdentityGeneration: "BY_DEFAULT"},
		},
		{
			name: "a start and an increment", dialect: "postgres",
			sql: "ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5);",
			want: &ast.AlterColumnOperation{
				ColumnName: "id", Action: ast.AlterColumnAddIdentity, IdentityGeneration: "BY_DEFAULT",
				IdentityStart: "100", IdentityIncrement: "5", IdentityOptions: "START WITH 100 INCREMENT BY 5",
			},
		},
		{
			name: "pg_dump spelling", dialect: "postgres",
			sql: "ALTER TABLE public.i_always ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (\n" +
				"    SEQUENCE NAME public.i_always_id_seq\n    START WITH 1\n    INCREMENT BY 1\n" +
				"    NO MINVALUE\n    NO MAXVALUE\n    CACHE 1\n);",
			want: &ast.AlterColumnOperation{
				ColumnName: "id", Action: ast.AlterColumnAddIdentity, IdentityGeneration: "ALWAYS",
				IdentityStart: "1", IdentityIncrement: "1",
				IdentityOptions: "SEQUENCE NAME public.i_always_id_seq\n    START WITH 1\n    INCREMENT BY 1\n" +
					"    NO MINVALUE\n    NO MAXVALUE\n    CACHE 1",
			},
		},
		{
			name: "CockroachDB", dialect: "cockroachdb",
			sql:  "ALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			want: &ast.AlterColumnOperation{ColumnName: "id", Action: ast.AlterColumnAddIdentity, IdentityGeneration: "ALWAYS"},
		},
		{
			name: "no dialect",
			sql:  "ALTER TABLE t ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY;",
			want: &ast.AlterColumnOperation{ColumnName: "id", Action: ast.AlterColumnAddIdentity, IdentityGeneration: "ALWAYS"},
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			operations := alterOperationsOf(c, test.dialect, test.sql)

			c.Assert(operations, qt.DeepEquals, []ast.AlterOperation{test.want})
		})
	}
}

// ADD GENERATED that is not an identity is refused, and so is the statement
// on a dialect whose ALTER COLUMN adds no identity.
func TestParse_AlterColumnAddIdentity_FailurePath(t *testing.T) {
	for _, test := range []struct {
		name, dialect, sql, wantErr string
	}{
		{
			name: "a generated expression", dialect: "postgres",
			sql:     "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS (b + 1) STORED;",
			wantErr: `line 1, column 34: expected AS IDENTITY after ALTER COLUMN a ADD GENERATED`,
		},
		{
			name: "a generation PostgreSQL does not have", dialect: "postgres",
			sql:     "ALTER TABLE t ALTER COLUMN a ADD GENERATED SOMETIMES AS IDENTITY;",
			wantErr: `line 1, column 44: expected ALWAYS or BY after GENERATED: got "SOMETIMES"`,
		},
		{
			name: "YugabyteDB", dialect: "yugabytedb",
			sql:     "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 1, column 30: unsupported ALTER COLUMN a ADD GENERATED: .*`,
		},
		{
			name: "MySQL", dialect: "mysql",
			sql:     "ALTER TABLE t ALTER COLUMN a ADD GENERATED ALWAYS AS IDENTITY;",
			wantErr: `line 1, column 30: unsupported ALTER COLUMN a ADD GENERATED: .*`,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			statements, err := parser.NewParser(test.sql, parser.WithDialect(test.dialect)).Parse()

			c.Assert(err, qt.ErrorMatches, test.wantErr)
			c.Assert(statements, qt.IsNil)
		})
	}
}

// ALTER TABLE ... REPLICA IDENTITY, which pg_dump writes for a table whose
// replica identity is not the default, is refused by name with what to do:
// the model has no replica identity to read it into. REPLICA followed by
// anything else keeps the refusal of an operation the parser does not know.
func TestParse_AlterTableReplicaIdentity_FailurePath(t *testing.T) {
	for _, test := range []struct {
		name, dialect, sql, wantErr string
	}{
		{
			name: "pg_dump spelling", dialect: "postgres",
			sql: "ALTER TABLE ONLY public.r_full REPLICA IDENTITY FULL;",
			wantErr: `line 1, column 32: unsupported ALTER TABLE public.r_full REPLICA IDENTITY FULL: ` +
				`Ptah does not model a table's replica identity; delete the statement from the schema file, ` +
				`and set the replica identity in a migration where a database needs it`,
		},
		{
			name: "an index, in a list of actions", dialect: "postgres",
			sql:     "ALTER TABLE r REPLICA IDENTITY USING INDEX r_pkey, ADD COLUMN b int;",
			wantErr: `line 1, column 15: unsupported ALTER TABLE r REPLICA IDENTITY USING INDEX r_pkey: Ptah does not model .*`,
		},
		{
			name:    "no dialect",
			sql:     "ALTER TABLE r REPLICA IDENTITY NOTHING;",
			wantErr: `line 1, column 15: unsupported ALTER TABLE r REPLICA IDENTITY NOTHING: Ptah does not model .*`,
		},
		{
			name: "REPLICA without IDENTITY", dialect: "postgres",
			sql:     "ALTER TABLE r REPLICA FULL;",
			wantErr: `line 1, column 15: unsupported ALTER operation: REPLICA`,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			statements, err := parser.NewParser(test.sql, parser.WithDialect(test.dialect)).Parse()

			c.Assert(err, qt.ErrorMatches, test.wantErr)
			c.Assert(statements, qt.IsNil)
		})
	}
}
