const gadgetKind schemaext.Kind = "example.org/custom/gadget"

// gadget is an object of the owner example.org/custom.
type gadget struct {
	Size string
}

func (*gadget) Kind() schemaext.Kind { return gadgetKind }

func (g *gadget) Clone() schemaext.Value { return new(*g) }

func (g *gadget) Equal(other schemaext.Value) bool {
	o, ok := other.(*gadget)
	return ok && *o == *g
}

func gadgetCodec() schemaext.Codec {
	encode := func(value schemaext.Payload) (json.RawMessage, error) { return json.Marshal(value.(*gadget).Size) }
	return schemaext.Codec{Prototype: &gadget{}, Representation: schemaext.Desired, Version: 1,
		Definition: json.RawMessage(`{"type":"string"}`),
		Clone:      func(value schemaext.Payload) (schemaext.Payload, error) { return value.(*gadget).Clone(), nil },
		Encode:     encode, Canonical: encode,
		Decode: func(data json.RawMessage) (schemaext.Payload, error) {
			size, err := schemaext.DecodeJSON[string](data)
			return &gadget{Size: size}, err
		},
	}
}

// gadgetObject is a gadget named name in schema, scoped to targets.
func gadgetObject(schema, name, size string, targets ...string) schemaext.Object {
	ref := objectidentity.ID{Kind: objectidentity.Kind(gadgetKind),
		Schema: objectidentity.Part{Source: schema, Normalized: schema}, Name: objectidentity.Part{Source: name, Normalized: name}}
	return schemaext.Object{Ref: ref, Value: &gadget{Size: size}, Targets: targets}
}

// gadgetEncoder writes each gadget as a block whose type is its size, in its
// schema unless the gadget is sized "database", bound to the targets of
// bound, and refuses a gadget sized "broken".
type gadgetEncoder struct {
	bound []string
}

func (e gadgetEncoder) EncodeHCL(_ context.Context, request hclext.EncodeRequest) (hclext.EncodeResult, error) {
	blocks := make([]hclext.EncodedBlock, 0, len(request.Objects))
	for _, object := range request.Objects {
		size := object.Value.(*gadget).Size
		if size == "broken" {
			return hclext.EncodeResult{}, errors.New("gadget is broken")
		}
		blocks = append(blocks, hclext.EncodedBlock{Type: size, Placement: hclext.AfterTables,
			Schema: object.Ref.Schema.Source, SchemaIsAddress: size == "database", Name: object.Ref.Name.Source,
			Object: object.Ref, Targets: e.bound,
			Attributes: []hclext.EncodedAttribute{
				{Name: "note", Value: hclext.Value{Kind: hclext.String, Text: "a \"quoted\" note"}},
				{Name: "on", Value: hclext.Value{Kind: hclext.Bool, Bool: true}},
			}})
	}
	return hclext.EncodeResult{Blocks: blocks}, nil
}

// gadgetOwners registers the owner example.org/custom through the runtime,
// writing its gadgets with encoder.
func gadgetOwners(encoder hclext.Encoder) hclext.Set {
	return must.Must(engine.New(engine.Provider{
		ID:     "example.org/custom",
		Codecs: []schemaext.Codec{gadgetCodec()},
		HCL:    []hclext.Extension{{Owner: "example.org/custom", Kinds: []schemaext.Kind{gadgetKind}, Encoder: encoder}},
	})).HCL()
}

// gadgetDocument is a table and the given gadgets.
func gadgetDocument(objects ...schemaext.Object) *schemamodel.Database {
	return &schemamodel.Database{
		Tables:         []schemamodel.Table{{StructName: "T", Name: "t"}},
		Fields:         []schemamodel.Field{{StructName: "T", Name: "id", Type: "INTEGER"}},
		FeatureObjects: must.Must(schemaext.NewObjects(objects...)),
	}
}

// TestRender_WritesAnOwnersBlock writes the block an owner encodes after the
// tables: its label, its schema as a reference to a schema the document then
// declares, and its attributes as the owner orders them, a string quoted and
// a bool bare.
func TestRender_WritesAnOwnersBlock(t *testing.T) {
	c := qt.New(t)

	result, err := atlashclrender.Render(gadgetDocument(gadgetObject("app", "g", "widget")),
		atlashclrender.Options{HCL: gadgetOwners(gadgetEncoder{})})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Equals, "// Code generated by ptah; DO NOT EDIT.\n\n"+
		"schema \"app\" {\n}\n\n"+
		"table \"t\" {\n  column \"id\" {\n    type = INTEGER\n  }\n}\n\n"+
		"widget \"g\" {\n  schema = schema.app\n  note = \"a \\\"quoted\\\" note\"\n  on = true\n}\n\n")
	c.Assert(result.Diagnostics, qt.HasLen, 0)
}

// TestRender_OrdersTheBlocksAfterTheTables orders every block after the tables
// by type, schema and name, whichever wrote it: an owner's block of type
// "aardvark" comes before a YDB coordination node this package writes itself,
// and one of type "zebra" after it.
func TestRender_OrdersTheBlocksAfterTheTables(t *testing.T) {
	c := qt.New(t)
	db := gadgetDocument(gadgetObject("", "b", "zebra"), gadgetObject("", "z", "aardvark"), gadgetObject("", "a", "aardvark"),
		ydbcoordination.DesiredObject("", "locks", "", ydbcoordination.Spec{}))

	result, err := atlashclrender.Render(db, atlashclrender.Options{HCL: gadgetOwners(gadgetEncoder{})})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Contains, "\naardvark \"a\" {\n  note = \"a \\\"quoted\\\" note\"\n  on = true\n}\n\n"+
		"aardvark \"z\" {\n  note = \"a \\\"quoted\\\" note\"\n  on = true\n}\n\n"+
		"coordination_node \"locks\" {\n}\n\n"+
		"zebra \"b\" {\n  note = \"a \\\"quoted\\\" note\"\n  on = true\n}\n")
}

// TestRenderInspected_FillsAnOwnersEmptySchema writes an owner's block with
// no schema in the inspected document's default schema, unless the block's
// empty schema is an address of its own.
func TestRenderInspected_FillsAnOwnersEmptySchema(t *testing.T) {
	tests := []struct {
		name string
		size string
		want string
	}{
		{name: "a block in no schema", size: "widget", want: "widget \"g\" {\n  schema = schema.dbo\n  note"},
		{name: "a block whose empty schema is an address", size: "database", want: "database \"g\" {\n  note"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			result, err := atlashclrender.RenderInspected(gadgetDocument(gadgetObject("", "g", test.size)), "dbo",
				atlashclrender.Options{HCL: gadgetOwners(gadgetEncoder{}), Dialect: platform.SQLServer})

			c.Assert(err, qt.IsNil)
			c.Assert(string(result.Data), qt.Contains, test.want)
		})
	}
}

// TestRender_ReportsAnObjectNoOwnerWrites reports an owner's object as one HCL
// does not represent when no selected owner writes it, and writes it
// otherwise.
func TestRender_ReportsAnObjectNoOwnerWrites(t *testing.T) {
	tests := []struct {
		name  string
		owner hclext.Set
		want  []atlashclrender.Diagnostic
	}{
		{name: "without the owner", owner: hclext.None(), want: []atlashclrender.Diagnostic{{Severity: atlashclrender.SeverityWarning,
			Path:    `features["example.org/custom/gadget"][""][""][""]["g"][""]`,
			Message: `feature object example.org/custom/gadget g of kind example.org/custom/gadget is not represented in HCL`}}},
		{name: "with the owner", owner: gadgetOwners(gadgetEncoder{})},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			result, err := atlashclrender.Render(gadgetDocument(gadgetObject("", "g", "widget")), atlashclrender.Options{HCL: test.owner})

			c.Assert(err, qt.IsNil)
			c.Assert(result.Diagnostics, qt.DeepEquals, test.want)
		})
	}
}

// TestRender_KeepsAScopeTheBlockBindsAgain reports an owner's object scoped
// to some targets as a loss unless reading its block back binds it to exactly
// those targets again.
func TestRender_KeepsAScopeTheBlockBindsAgain(t *testing.T) {
	tests := []struct {
		name  string
		bound []string
		want  int
	}{
		{name: "the block binds the scope", bound: []string{platform.SQLServer, platform.Oracle}, want: 0},
		{name: "the block binds another scope", bound: []string{platform.SQLServer}, want: 1},
		{name: "the block binds none", want: 1},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			db := gadgetDocument(gadgetObject("", "g", "widget", platform.Oracle, platform.SQLServer))

			result, err := atlashclrender.Render(db, atlashclrender.Options{HCL: gadgetOwners(gadgetEncoder{bound: test.bound})})

			c.Assert(err, qt.IsNil)
			c.Assert(result.Diagnostics, qt.HasLen, test.want)
		})
	}
}

// TestRender_FailurePath refuses a render without a selected owner set, and
// one an owner cannot write.
func TestRender_FailurePath(t *testing.T) {
	tests := []struct {
		name    string
		owners  hclext.Set
		wantErr string
	}{
		{name: "no owner set", wantErr: `no HCL schema owners were selected`},
		{name: "an owner's refusal", owners: gadgetOwners(gadgetEncoder{}), wantErr: `gadget is broken`},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			result, err := atlashclrender.Render(gadgetDocument(gadgetObject("", "g", "broken")), atlashclrender.Options{HCL: test.owners})

			c.Assert(err, qt.ErrorMatches, test.wantErr)
			c.Assert(result.Data, qt.IsNil)
		})
	}
}
