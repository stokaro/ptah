package atlashclrender_test

import (
	"testing"

	qt "github.com/frankban/quicktest"
	"github.com/go-extras/go-kit/must"

	"ptah.run/core/schemaext"
	"ptah.run/core/schemamodel"
	"ptah.run/dialect/mysql/mysqlschema"
	"ptah.run/internal/atlashclrender"
	"ptah.run/internal/builtintest"
)

// TestRenderInspected_WritesTheMySQLOptions writes the MySQL owner's options
// through the runtime's owners where the community binary reads them: the
// table's engine in place of the common one, its charset and its
// auto_increment, a column's ON UPDATE and charset, and a FULLTEXT index's
// parser. The primary key's COMMENT and its block size are each reported, the
// first by the writer and the second by the owner.
func TestRenderInspected_WritesTheMySQLOptions(t *testing.T) {
	c := qt.New(t)
	db := &schemamodel.Database{
		Tables: []schemamodel.Table{{StructName: "Order", Name: "orders", Engine: "MyISAM", PrimaryKey: []string{"id"}, PrimaryKeyComment: "key",
			PrimaryKeyFacets: must.Must(mysqlschema.WithIndexBlockSize(schemaext.Facets{}, 8)),
			Facets:           must.Must(schemaext.NewFacets(&mysqlschema.DesiredTable{Engine: "InnoDB", AutoIncrement: "100", Charset: "utf8mb4"}))}},
		Fields: []schemamodel.Field{
			{StructName: "Order", Name: "id", Type: "INT", Primary: true},
			{StructName: "Order", Name: "note", Type: "TEXT", Facets: must.Must(mysqlschema.WithColumnSettings(schemaext.Facets{},
				mysqlschema.ColumnSettings{Charset: "latin1"}))},
			{StructName: "Order", Name: "changed", Type: "TIMESTAMP", DefaultExpr: "CURRENT_TIMESTAMP",
				Facets: must.Must(mysqlschema.WithColumnSettings(schemaext.Facets{}, mysqlschema.ColumnSettings{OnUpdate: "CURRENT_TIMESTAMP"}))},
		},
		Indexes: []schemamodel.Index{{StructName: "Order", Name: "ft_note", TableName: "orders", Type: "FULLTEXT", Fields: []string{"note"},
			Facets: must.Must(mysqlschema.WithIndexOptions(schemaext.Facets{}, mysqlschema.DesiredIndex{Parser: "ngram"}))}},
	}

	result, err := atlashclrender.RenderInspected(db, "", atlashclrender.Options{HCL: builtintest.Runtime().HCL(), Dialect: "mysql"})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Equals, `// Code generated by ptah; DO NOT EDIT.
// ptah:not-described range

table "orders" {
  engine = "InnoDB"
  charset = "utf8mb4"
  auto_increment = 100
  column "id" {
    type = INT
  }
  column "note" {
    type = TEXT
    charset = "latin1"
  }
  column "changed" {
    type = TIMESTAMP
    default = sql("CURRENT_TIMESTAMP")
    on_update = sql("CURRENT_TIMESTAMP")
  }
  primary_key {
    columns = [column.id]
  }
  index "ft_note" {
    type = "FULLTEXT"
    parser = "ngram"
    columns = [column.note]
  }
}

`)
	c.Assert(result.Diagnostics, qt.DeepEquals, []atlashclrender.Diagnostic{
		{Severity: atlashclrender.SeverityWarning, Path: `tables["orders"].primary_key`, Message: "the primary key COMMENT option cannot be represented in HCL schema output"},
		{Severity: atlashclrender.SeverityWarning, Path: `tables["orders"].primary_key`, Message: "the primary key KEY_BLOCK_SIZE option cannot be represented in HCL schema output"},
	})
}
