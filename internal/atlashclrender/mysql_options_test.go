// TestRenderInspected_WritesTheMySQLOptions writes the MySQL owner's options
// through the runtime's owners where the community binary reads them: the
// table's engine in place of the common one, its charset and its
// auto_increment, a column's ON UPDATE and charset, and a FULLTEXT index's
// parser. The primary key's COMMENT and its block size are each reported, the
// first by the writer and the second by the owner.
func TestRenderInspected_WritesTheMySQLOptions(t *testing.T) {
	c := qt.New(t)
	db := &schemamodel.Database{
		Tables: []schemamodel.Table{{StructName: "Order", Name: "orders", Engine: "MyISAM", PrimaryKey: []string{"id"}, PrimaryKeyComment: "key",
			PrimaryKeyFacets: must.Must(mysqlschema.WithIndexBlockSize(schemaext.Facets{}, 8)),
			Facets:           must.Must(schemaext.NewFacets(&mysqlschema.DesiredTable{Engine: "InnoDB", AutoIncrement: "100", Charset: "utf8mb4"}))}},
		Fields: []schemamodel.Field{
			{StructName: "Order", Name: "id", Type: "INT", Primary: true},
			{StructName: "Order", Name: "note", Type: "TEXT", Facets: must.Must(mysqlschema.WithColumnSettings(schemaext.Facets{},
				mysqlschema.ColumnSettings{Charset: "latin1"}))},
			{StructName: "Order", Name: "changed", Type: "TIMESTAMP", DefaultExpr: "CURRENT_TIMESTAMP",
				Facets: must.Must(mysqlschema.WithColumnSettings(schemaext.Facets{}, mysqlschema.ColumnSettings{OnUpdate: "CURRENT_TIMESTAMP"}))},
		},
		Indexes: []schemamodel.Index{{StructName: "Order", Name: "ft_note", TableName: "orders", Type: "FULLTEXT", Fields: []string{"note"},
			Facets: must.Must(mysqlschema.WithIndexOptions(schemaext.Facets{}, mysqlschema.DesiredIndex{Parser: "ngram"}))}},
	}

	result, err := atlashclrender.RenderInspected(db, "", atlashclrender.Options{HCL: builtintest.Runtime().HCL(), Dialect: "mysql"})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Equals, `// Code generated by ptah; DO NOT EDIT.

table "orders" {
  engine = "InnoDB"
  charset = "utf8mb4"
  auto_increment = 100
  column "id" {
    type = INT
  }
  column "note" {
    type = TEXT
    charset = "latin1"
  }
  column "changed" {
    type = TIMESTAMP
    default = sql("CURRENT_TIMESTAMP")
    on_update = sql("CURRENT_TIMESTAMP")
  }
  primary_key {
    columns = [column.id]
  }
  index "ft_note" {
    type = "FULLTEXT"
    parser = "ngram"
    columns = [column.note]
  }
}

`)
	c.Assert(result.Diagnostics, qt.DeepEquals, []atlashclrender.Diagnostic{
		{Severity: atlashclrender.SeverityWarning, Path: `tables["orders"].primary_key`, Message: "the primary key COMMENT option cannot be represented in HCL schema output"},
		{Severity: atlashclrender.SeverityWarning, Path: `tables["orders"].primary_key`, Message: "the primary key KEY_BLOCK_SIZE option cannot be represented in HCL schema output"},
	})
}

// tableCollationDatabase is a MySQL schema whose tables take its charset and
// collation, take another collation of its charset, and take another charset.
func tableCollationDatabase() *schemamodel.Database {
	table := func(name, charset, collate string) schemamodel.Table {
		return schemamodel.Table{StructName: name, Name: name, Schema: "shop", Collate: collate,
			Facets: must.Must(mysqlschema.WithObservedTable(schemaext.Facets{}, charset))}
	}
	return &schemamodel.Database{
		Schemas: []schemamodel.Schema{{Name: "shop", Charset: "utf8mb4", Collate: "utf8mb4_unicode_ci"}},
		Tables: []schemamodel.Table{
			table("same", "utf8mb4", "utf8mb4_unicode_ci"),
			table("binary", "utf8mb4", "utf8mb4_bin"),
			table("legacy", "latin1", "latin1_swedish_ci"),
		},
	}
}

// TestRenderInspected_LeavesATableCollationItsSchemaDeclaresToTheSchema pins
// the table attributes of an inspected MySQL schema to what the pinned
// community binary v1.3.0 writes, measured on MySQL 8.4: a charset or a
// collate equal to the schema block's is left to it, and one that differs is
// written.
func TestRenderInspected_LeavesATableCollationItsSchemaDeclaresToTheSchema(t *testing.T) {
	c := qt.New(t)

	result, err := atlashclrender.RenderInspected(tableCollationDatabase(), "", atlashclrender.Options{HCL: builtintest.Runtime().HCL(), Dialect: "mysql"})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Equals, `// Code generated by ptah; DO NOT EDIT.

schema "shop" {
  charset = "utf8mb4"
  collate = "utf8mb4_unicode_ci"
}

table "binary" {
  schema = schema.shop
  collate = "utf8mb4_bin"
}

table "legacy" {
  schema = schema.shop
  charset = "latin1"
  collate = "latin1_swedish_ci"
}

table "same" {
  schema = schema.shop
}

`)
}

// TestRender_WritesTheTableCollationADeclarationStates keeps every table
// attribute of a declaration, one that restates its schema's included: the
// document says what its author wrote.
func TestRender_WritesTheTableCollationADeclarationStates(t *testing.T) {
	c := qt.New(t)

	result, err := atlashclrender.Render(tableCollationDatabase(), atlashclrender.Options{HCL: builtintest.Runtime().HCL(), Dialect: "mysql"})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Contains, `table "same" {
  schema = schema.shop
  charset = "utf8mb4"
  collate = "utf8mb4_unicode_ci"
}
`)
}
