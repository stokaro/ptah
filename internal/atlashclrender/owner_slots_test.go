// slotWriter writes, into every block of the writer it is handed, the
// attributes and the losses named by the size of the gadget the block's
// facets hold.
type slotWriter struct {
	attributes map[string][]hclext.EncodedAttribute
	losses     map[string][]string
}

func (e slotWriter) EncodeHCL(_ context.Context, request hclext.EncodeRequest) (hclext.EncodeResult, error) {
	var result hclext.EncodeResult
	write := func(slot hclext.Slot, facets schemaext.Facets) {
		value, _, _ := schemaext.FacetAs[*gadget](facets, gadgetKind)
		result.Attributes = append(result.Attributes, hclext.SlotAttributes{Slot: slot, Attributes: e.attributes[value.Size], Losses: e.losses[value.Size]})
	}
	for _, table := range request.Tables {
		write(hclext.Slot{Kind: hclext.SlotTable, Table: table.Table}, table.Facets)
	}
	for _, slot := range slices.Concat(request.Columns, request.Indexes, request.Keys) {
		write(slot.Slot, slot.Facets)
	}
	return result, nil
}

// gadgetFacets are facets holding a gadget of size.
func gadgetFacets(size string) schemaext.Facets {
	return must.Must(schemaext.NewFacets(&gadget{Size: size}))
}

// writtenSlots is the slotWriter TestRender_WritesAnOwnersAttributesIntoItsBlocks
// renders with.
func writtenSlots() slotWriter {
	text := func(name, value string) hclext.EncodedAttribute {
		return hclext.EncodedAttribute{Name: name, Value: hclext.Value{Kind: hclext.String, Text: value}}
	}
	yes := func(name string) hclext.EncodedAttribute {
		return hclext.EncodedAttribute{Name: name, Value: hclext.Value{Kind: hclext.Bool, Bool: true}}
	}
	return slotWriter{
		attributes: map[string][]hclext.EncodedAttribute{
			"table": {yes("without_rowid"), {Name: "auto_increment", Value: hclext.Value{Kind: hclext.Number, Text: "42"}}, yes("strict"),
				text("charset", "utf8mb4"), text("engine", "owned")},
			"column": {text("charset", "latin1"), {Name: "on_update", Value: hclext.Value{Kind: hclext.SQL, Text: `now("x") ${y}`}}},
			"index":  {text("parser", "ngram")},
		},
		losses: map[string][]string{"table": {"table lost"}, "column": {"column lost"}, "key": {"key lost"}, "index": {"index lost"}},
	}
}

// TestRender_WritesAnOwnersAttributesIntoItsBlocks writes the attributes an
// owner gives this writer's blocks where the Atlas layout places them,
// whatever order the owner gives them in: a table's engine in place of the
// common one, a number bare and SQL text as an sql() call it never
// evaluates. Each loss is reported at the path the writer names the block
// with, the primary key's after the writer's own COMMENT loss, and a check
// constraint's although Atlas writes its own block for it.
func TestRender_WritesAnOwnersAttributesIntoItsBlocks(t *testing.T) {
	c := qt.New(t)
	db := &schemamodel.Database{
		Tables: []schemamodel.Table{
			{StructName: "T", Name: "t", Engine: "common", APIName: "api", Collate: "c", Comment: "cm", Facets: gadgetFacets("table"),
				PrimaryKey: []string{"id"}, PrimaryKeyComment: "pk", PrimaryKeyFacets: gadgetFacets("key")},
			{StructName: "U", Name: "u", Engine: "common", Facets: gadgetFacets("nothing")},
		},
		Fields: []schemamodel.Field{
			{StructName: "T", Name: "id", Type: "INTEGER", DefaultExpr: "1", Check: "id > 0", CheckName: "ck_id", Collate: "co", Facets: gadgetFacets("column")},
			{StructName: "U", Name: "id", Type: "INTEGER"},
		},
		Indexes: []schemamodel.Index{{StructName: "T", Name: "i", Type: "FULLTEXT", Condition: "id > 1", Fields: []string{"id"}, Facets: gadgetFacets("index")}},
		Constraints: []schemamodel.Constraint{{StructName: "T", Table: "t", Name: "ck", Type: "CHECK", CheckExpression: "id > 2",
			Facets: gadgetFacets("key")}},
	}

	result, err := atlashclrender.Render(db, atlashclrender.Options{HCL: gadgetOwners(writtenSlots())})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Equals, `// Code generated by ptah; DO NOT EDIT.

table "t" {
  engine = "owned"
  api_name = "api"
  charset = "utf8mb4"
  collate = "c"
  comment = "cm"
  auto_increment = 42
  strict = true
  without_rowid = true
  column "id" {
    type = INTEGER
    default = sql("1")
    on_update = sql("now(\"x\") $${y}")
    check = "id > 0"
    check_name = "ck_id"
    charset = "latin1"
    collate = "co"
  }
  primary_key {
    columns = [column.id]
  }
  check "ck" {
    expr = "id > 2"
  }
  index "i" {
    type = "FULLTEXT"
    parser = "ngram"
    where = "id > 1"
    columns = [column.id]
  }
}

table "u" {
  engine = "common"
  column "id" {
    type = INTEGER
  }
}

`)
	c.Assert(result.Diagnostics, qt.DeepEquals, []atlashclrender.Diagnostic{
		{Severity: atlashclrender.SeverityWarning, Path: "table.t", Message: "table lost"},
		{Severity: atlashclrender.SeverityWarning, Path: "column.T.id", Message: "column lost"},
		{Severity: atlashclrender.SeverityWarning, Path: `tables["t"].primary_key`, Message: "the primary key COMMENT option cannot be represented in HCL schema output"},
		{Severity: atlashclrender.SeverityWarning, Path: `tables["t"].primary_key`, Message: "key lost"},
		{Severity: atlashclrender.SeverityWarning, Path: `constraints["ck"]`, Message: "key lost"},
		{Severity: atlashclrender.SeverityWarning, Path: `indexes["T"]["i"]`, Message: "index lost"},
	})
}

// TestRender_GivesAnOwnersAttributesToTheBlockThatHoldsTheFacets writes an
// owner's attributes into the index whose facets it was handed, and not into
// another index of the same name that holds none.
func TestRender_GivesAnOwnersAttributesToTheBlockThatHoldsTheFacets(t *testing.T) {
	c := qt.New(t)
	db := gadgetDocument()
	db.Indexes = []schemamodel.Index{{StructName: "T", Name: "i", Fields: []string{"id"}, Facets: gadgetFacets("index")},
		{StructName: "T", Name: "i", Type: "BTREE", Fields: []string{"id"}}}

	result, err := atlashclrender.Render(db, atlashclrender.Options{HCL: gadgetOwners(writtenSlots())})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Contains, "  index \"i\" {\n    parser = \"ngram\"\n    columns = [column.id]\n  }\n"+
		"  index \"i\" {\n    type = \"BTREE\"\n    columns = [column.id]\n  }\n")
}

// TestRender_RefusesAnOwnersAttribute_FailurePath refuses an attribute a
// block has no place for, and two blocks of one name that both hold an
// owner's facets, which HCL cannot tell apart.
func TestRender_RefusesAnOwnersAttribute_FailurePath(t *testing.T) {
	misplaced := slotWriter{attributes: map[string][]hclext.EncodedAttribute{
		"column": {{Name: "comment", Value: hclext.Value{Kind: hclext.String, Text: "c"}}}}}
	tests := []struct {
		name    string
		indexes []schemamodel.Index
		field   schemaext.Facets
		wantErr string
	}{
		{name: "an attribute with no place", field: gadgetFacets("column"),
			wantErr: `an HCL encoder wrote attribute "comment" of column "id" of table "t", which the writer has no place for`},
		{name: "two indexes of one name", indexes: []schemamodel.Index{{StructName: "T", Name: "i", Fields: []string{"id"}, Facets: gadgetFacets("index")},
			{StructName: "T", Name: "i", Fields: []string{"id"}, Facets: gadgetFacets("other")}},
			wantErr: `the document writes index "i" of table "t" twice with owner settings, which HCL cannot tell apart`},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			db := gadgetDocument()
			db.Fields[0].Facets = test.field
			db.Indexes = test.indexes

			result, err := atlashclrender.Render(db, atlashclrender.Options{HCL: gadgetOwners(misplaced)})

			c.Assert(err, qt.ErrorMatches, test.wantErr)
			c.Assert(result.Data, qt.IsNil)
		})
	}
}
