// sqlAttribute is an attribute an owner writes as SQL.
func sqlAttribute(name, text string) hclext.EncodedAttribute {
	return hclext.EncodedAttribute{Name: name, Value: hclext.Value{Kind: hclext.SQL, Text: text}}
}

// emptyDocument is a document that holds nothing of its own.
func emptyDocument() *schemamodel.Database {
	return &schemamodel.Database{FeatureObjects: must.Must(schemaext.NewObjects())}
}

// TestRender_WritesAnOwnersCompositeAsTheCommonOneIs renders one composite
// type twice, once from the common model and once as an owner's block with a
// child for each field, and gets the same bytes: the children are what lets
// an owner write the composite blocks the common model writes today.
func TestRender_WritesAnOwnersCompositeAsTheCommonOneIs(t *testing.T) {
	c := qt.New(t)
	common := emptyDocument()
	common.CompositeTypes = []schemamodel.CompositeType{{Schema: "app", Name: "addr", Comment: "where",
		Fields: []schemamodel.CompositeField{{Name: "street", Type: "text"}, {Name: "zip", Type: "character varying(10)"}}}}
	owned := gadgetOwners(blocksEncoder{blocks: []hclext.EncodedBlock{{Type: "composite", Placement: hclext.UserTypes, Schema: "app", Name: "addr",
		Attributes: []hclext.EncodedAttribute{{Name: "comment", Value: hclext.Value{Kind: hclext.String, Text: "where"}}},
		Children: []hclext.EncodedChild{
			{Type: "field", Name: "street", Attributes: []hclext.EncodedAttribute{sqlAttribute("type", "text")}},
			{Type: "field", Name: "zip", Attributes: []hclext.EncodedAttribute{sqlAttribute("type", "character varying(10)")}},
		}}}})

	fromCommon, commonErr := atlashclrender.Render(common, atlashclrender.Options{HCL: hclext.None()})
	fromOwner, ownerErr := atlashclrender.Render(emptyDocument(), atlashclrender.Options{HCL: owned})

	c.Assert(commonErr, qt.IsNil)
	c.Assert(ownerErr, qt.IsNil)
	c.Assert(string(fromOwner.Data), qt.Equals, string(fromCommon.Data))
	c.Assert(string(fromCommon.Data), qt.Equals, "// Code generated by ptah; DO NOT EDIT.\n\n"+
		"schema \"app\" {\n}\n\n"+
		"composite \"addr\" {\n  schema = schema.app\n  comment = \"where\"\n"+
		"  field \"street\" {\n    type = sql(\"text\")\n  }\n"+
		"  field \"zip\" {\n    type = sql(\"character varying(10)\")\n  }\n}\n\n")
}

// TestRender_WritesAnOwnersChildrenInItsOrder writes a block's children after
// its attributes in the owner's order, which is not sorted, each with its
// label and its attributes one level further in, a child without attributes
// included.
func TestRender_WritesAnOwnersChildrenInItsOrder(t *testing.T) {
	c := qt.New(t)
	owners := gadgetOwners(blocksEncoder{blocks: []hclext.EncodedBlock{{Type: "shape", Placement: hclext.UserTypes, Name: "s",
		Attributes: []hclext.EncodedAttribute{{Name: "on", Value: hclext.Value{Kind: hclext.Bool, Bool: true}}},
		Children: []hclext.EncodedChild{
			{Type: "member", Name: "zeta", Attributes: []hclext.EncodedAttribute{sqlAttribute("kind", "int4"),
				{Name: "note", Value: hclext.Value{Kind: hclext.String, Text: "last"}}}},
			{Type: "member", Name: "alpha", Attributes: []hclext.EncodedAttribute{sqlAttribute("kind", "text")}},
			{Type: "member", Name: "mid"},
		}}}})

	result, err := atlashclrender.Render(emptyDocument(), atlashclrender.Options{HCL: owners})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Equals, "// Code generated by ptah; DO NOT EDIT.\n\n"+
		"shape \"s\" {\n  on = true\n"+
		"  member \"zeta\" {\n    kind = sql(\"int4\")\n    note = \"last\"\n  }\n"+
		"  member \"alpha\" {\n    kind = sql(\"text\")\n  }\n"+
		"  member \"mid\" {\n  }\n}\n\n")
}

// blockLabels are the type and first label of each top-level block of an HCL
// document, in order.
var blockLabels = regexp.MustCompile(`(?m)^([a-z_]+) "([^"]*)"`)

// TestRender_OrdersTypeBlocksAmongTheOwners writes the common model's
// domains, composite types and ranges and the owners' blocks among the types
// as one placement, after the sequences and before the enums, ordered by
// type, schema and name whoever wrote a block: a domain without a schema
// comes before one in app, and an owner's block of each type stands among the
// common model's by its name.
func TestRender_OrdersTypeBlocksAmongTheOwners(t *testing.T) {
	c := qt.New(t)
	document := emptyDocument()
	document.Sequences = []schemamodel.Sequence{{Name: "s", AsType: "bigint"}}
	document.Enums = []schemamodel.Enum{{Name: "e", Values: []string{"a"}}}
	document.Domains = []schemamodel.Domain{{Schema: "app", Name: "b", BaseType: "int4"}, {Name: "z", BaseType: "int4"}}
	document.CompositeTypes = []schemamodel.CompositeType{{Schema: "app", Name: "c", Fields: []schemamodel.CompositeField{{Name: "f", Type: "int4"}}}}
	document.Ranges = []schemamodel.Range{{Schema: "app", Name: "r", Subtype: "int4"}}
	owners := gadgetOwners(blocksEncoder{blocks: []hclext.EncodedBlock{
		{Type: "range", Placement: hclext.UserTypes, Schema: "app", Name: "q", Attributes: []hclext.EncodedAttribute{sqlAttribute("subtype", "int8")}},
		{Type: "domain", Placement: hclext.UserTypes, Schema: "app", Name: "a", Attributes: []hclext.EncodedAttribute{sqlAttribute("type", "int8")}},
		{Type: "composite", Placement: hclext.UserTypes, Schema: "app", Name: "b", Children: []hclext.EncodedChild{
			{Type: "field", Name: "f", Attributes: []hclext.EncodedAttribute{sqlAttribute("type", "int8")}}}},
	}})

	result, err := atlashclrender.Render(document, atlashclrender.Options{HCL: owners})

	c.Assert(err, qt.IsNil)
	c.Assert(blockLabels.FindAllString(string(result.Data), -1), qt.DeepEquals, []string{
		`schema "app"`, `sequence "s"`, `composite "b"`, `composite "c"`, `domain "z"`, `domain "a"`, `domain "b"`, `range "q"`, `range "r"`, `enum "e"`,
	})
}
