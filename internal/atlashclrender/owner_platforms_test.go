package atlashclrender_test

import (
	"context"
	"testing"

	qt "github.com/frankban/quicktest"
	"github.com/go-extras/go-kit/must"

	"ptah.run/core/hclext"
	"ptah.run/core/schemaext"
	"ptah.run/core/schemamodel"
	"ptah.run/engine"
	"ptah.run/internal/atlashclrender"
)

// platformWriter writes the overrides of the custom platform group into each
// table it is handed, and the loss of the part the group does not hold.
type platformWriter struct {
	overrides []hclext.PlatformOverride
	loss      string
}

func (e platformWriter) EncodeHCL(_ context.Context, request hclext.EncodeRequest) (hclext.EncodeResult, error) {
	var result hclext.EncodeResult
	for _, table := range request.Tables {
		written := hclext.SlotAttributes{Slot: hclext.Slot{Kind: hclext.SlotTable, Table: table.Table}, Overrides: e.overrides}
		if e.loss != "" {
			written.Losses = []string{e.loss}
		}
		result.Attributes = append(result.Attributes, written)
	}
	return result, nil
}

// platformDecoder decodes nothing; the writer's tests read no document.
type platformDecoder struct{}

func (platformDecoder) DecodeHCL(context.Context, hclext.Request) (hclext.Result, error) {
	return hclext.Result{}, nil
}

// platformOwners is an owner of the custom platform group that writes with
// encoder.
func platformOwners(encoder hclext.Encoder) hclext.Set {
	return must.Must(engine.New(engine.Provider{
		ID:     "example.org/custom",
		Codecs: []schemaext.Codec{gadgetCodec()},
		HCL: []hclext.Extension{{Owner: "example.org/custom", Kinds: []schemaext.Kind{gadgetKind}, Encoder: encoder, Decoder: platformDecoder{},
			Blocks: []hclext.Block{{Site: hclext.TablePlatform, Type: "custom", Attributes: []hclext.Attribute{{Name: "ttl", Kind: hclext.String}, {Name: "unit", Kind: hclext.String}}}}}},
	})).HCL()
}

// platformDocument is a table with a gadget and a platform group of another
// target.
func platformDocument() *schemamodel.Database {
	return &schemamodel.Database{
		Tables: []schemamodel.Table{{StructName: "T", Name: "t", Facets: gadgetFacets("table"),
			Overrides: map[string]map[string]string{"zeta": {"engine": "InnoDB"}, "alpha": {"mode": "fast"}}}},
		Fields: []schemamodel.Field{{StructName: "T", Name: "id", Type: "INTEGER"}},
	}
}

// TestRender_WritesAnOwnersPlatformGroup writes the overrides an owner gives a
// table as the table's platform block of the owner's type, among the table's
// own platform blocks and in their layout: labels and keys sorted, values
// quoted. The loss of the part the group does not hold is a warning at the
// table.
func TestRender_WritesAnOwnersPlatformGroup(t *testing.T) {
	c := qt.New(t)
	writer := platformWriter{overrides: []hclext.PlatformOverride{{Platform: "custom", Key: "unit", Value: "SECONDS"}, {Platform: "custom", Key: "ttl", Value: "P1D"}},
		loss: "the tiers are not represented in HCL"}

	result, err := atlashclrender.Render(platformDocument(), atlashclrender.Options{HCL: platformOwners(writer)})

	c.Assert(err, qt.IsNil)
	c.Assert(string(result.Data), qt.Equals, `// Code generated by ptah; DO NOT EDIT.

table "t" {
  platform "alpha" {
    override "mode" {
      value = "fast"
    }
  }
  platform "custom" {
    override "ttl" {
      value = "P1D"
    }
    override "unit" {
      value = "SECONDS"
    }
  }
  platform "zeta" {
    override "engine" {
      value = "InnoDB"
    }
  }
  column "id" {
    type = INTEGER
  }
}

`)
	c.Assert(result.Diagnostics, qt.DeepEquals, []atlashclrender.Diagnostic{{Severity: atlashclrender.SeverityWarning, Path: "table.t",
		Message: "the tiers are not represented in HCL"}})
}

// TestRender_RefusesAnOverrideTheTableHolds refuses an owner's override whose
// label and key the table's own overrides hold: the document would write it
// twice.
func TestRender_RefusesAnOverrideTheTableHolds(t *testing.T) {
	c := qt.New(t)
	db := platformDocument()
	db.Tables[0].Overrides["custom"] = map[string]string{"ttl": "P2D"}
	writer := platformWriter{overrides: []hclext.PlatformOverride{{Platform: "custom", Key: "ttl", Value: "P1D"}}}

	result, err := atlashclrender.Render(db, atlashclrender.Options{HCL: platformOwners(writer)})

	c.Assert(err, qt.ErrorMatches, `an HCL encoder wrote platform "custom" override "ttl" of table "t", which the table holds already`)
	c.Assert(result, qt.DeepEquals, atlashclrender.Result{})
}
