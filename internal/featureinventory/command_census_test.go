// TestCommandCensus_SeesTheTreeTheBinaryShips pins the size of each shipped
// tree.
//
// The numbers are here rather than derived, because the whole point of this
// package is that the previous census was short and nothing said so. The Phase 1
// audit walked `cmd.Commands()` on a constructed root and reported 85 native and
// 46 compatibility paths; the binaries answer 103 and 53. Six paths per binary
// are added by the initializers ExecuteC runs, and the native tree has since
// grown the `inference` namespace, which is eleven more.
//
// docs/agent-surface.md is generated by that same constructed-tree walk and is
// gated in CI. Its generated block holds 86 rows against 91 leaves, and the word
// `completion` appears in it zero times. A check built on the same walk would
// inherit the same blind spot and pass.
func TestCommandCensus_SeesTheTreeTheBinaryShips(t *testing.T) {
	tests := []struct {
		name    string
		tree    featureinventory.Tree
		paths   int
		visible int
		leaves  int
	}{
		{name: "native", tree: featureinventory.TreeNative, paths: 103, visible: 103, leaves: 91},
		{name: "compatibility", tree: featureinventory.TreeCompat, paths: 53, visible: 53, leaves: 46},
		{name: "compatibility, strict", tree: featureinventory.TreeCompatStrict, paths: 37, visible: 25, leaves: 33},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			census := shippedCensus(c)
			commands := census.OfTree(test.tree)
			leaves := countLeaves(commands)
			c.Assert(commands, qt.HasLen, test.paths)
			c.Assert(census.VisiblePaths(test.tree), qt.HasLen, test.visible)
			c.Assert(leaves, qt.Equals, test.leaves)

			// The five paths the audit's walk could not see, asserted by name.
			// A count alone would still pass if the census lost these and
			// gained five elsewhere.
			for _, path := range []string{"completion", "completion bash", "completion fish", "completion powershell", "completion zsh", "help"} {
				_, found := census.Lookup(test.tree, path)
				c.Assert(found, qt.IsTrue, qt.Commentf("the %s tree ships `%s` and the census did not find it", test.tree, path))
			}
		})
	}
}

// TestCommandCensus_TheConstructedTreeIsShortAndThisOneIsNot measures both
// numbers, which is the only way to show which of the two answers this package
// gives.
//
// A census that walked the constructed root would report 97 and 52. Asserting
// only the 103 would leave the claim "and the other method would have been
// wrong" unmeasured, so both are taken here, from the same roots, one walk
// apart.
func TestCommandCensus_TheConstructedTreeIsShortAndThisOneIsNot(t *testing.T) {
	tests := []struct {
		name        string
		tree        featureinventory.Tree
		constructed int
		shipped     int
		// missing is what the constructed walk cannot see. It differs between
		// the two binaries, and the difference is the reason a check must not
		// simply exempt `completion` and `help` by name: cmd/atlas calls
		// InitDefaultCompletionCmd at construction, so its constructed tree is
		// short by `help` alone.
		missing []string
	}{
		{
			name:        "native",
			tree:        featureinventory.TreeNative,
			constructed: 97,
			shipped:     103,
			missing:     []string{"completion", "completion bash", "completion fish", "completion powershell", "completion zsh", "help"},
		},
		{
			name:        "compatibility",
			tree:        featureinventory.TreeCompat,
			constructed: 52,
			shipped:     53,
			missing:     []string{"help"},
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)

			constructed := constructedPaths(shippedRoots()[test.tree])
			c.Assert(constructed, qt.HasLen, test.constructed)

			shipped := featureinventory.Walk(test.tree, shippedRoots()[test.tree])
			c.Assert(shipped, qt.HasLen, test.shipped)

			c.Assert(missingFrom(constructed, shipped), qt.DeepEquals, test.missing)
		})
	}
}

