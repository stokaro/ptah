// TestCommandCensus_RefusesAnEmptyTree is the control on every gate below.
//
// A census assembled from no roots would compare every document against nothing
// and find nothing wrong with any of them.
func TestCommandCensus_RefusesAnEmptyTree(t *testing.T) {
	t.Run("no trees at all", func(t *testing.T) {
		c := qt.New(t)
		census, err := featureinventory.NewCensus(make(map[featureinventory.Tree]*cobra.Command))
		c.Assert(err, qt.ErrorMatches, ".*no command trees to census.*")
		c.Assert(census, qt.IsNil)
	})
}

// TestCommandCensus_StrictModeRemovesPathsInTwoDistinguishableWays records what
// the strict profile does to the compatibility tree.
//
// The inventory needs this as a column rather than a footnote: 53 paths become
// 25, and the 28 that go do not go the same way. Sixteen are not registered at
// all, and twelve stay registered and hidden precisely so that invoking one
// produces a named abort instead of `unknown command`.
func TestCommandCensus_StrictModeRemovesPathsInTwoDistinguishableWays(t *testing.T) {
	c := qt.New(t)
	census := shippedCensus(c)

	counts := make(map[featureinventory.StrictPresence]int)
	for _, cmd := range census.OfTree(featureinventory.TreeCompat) {
		counts[census.StrictOf(cmd)]++
	}

	c.Assert(counts[featureinventory.StrictRegistered], qt.Equals, 25)
	c.Assert(counts[featureinventory.StrictGated], qt.Equals, 12)
	c.Assert(counts[featureinventory.StrictAbsent], qt.Equals, 16)
	c.Assert(counts[featureinventory.StrictGated]+counts[featureinventory.StrictAbsent], qt.Equals, 28)

	// One of each, by name, so a count that stayed right while the
	// classification moved is still a failure.
	gated, found := census.Lookup(featureinventory.TreeCompat, "schema plan")
	c.Assert(found, qt.IsTrue)
	c.Assert(census.StrictOf(gated), qt.Equals, featureinventory.StrictGated)

	absent, found := census.Lookup(featureinventory.TreeCompat, "migrate ls")
	c.Assert(found, qt.IsTrue)
	c.Assert(census.StrictOf(absent), qt.Equals, featureinventory.StrictAbsent)

	kept, found := census.Lookup(featureinventory.TreeCompat, "migrate apply")
	c.Assert(found, qt.IsTrue)
	c.Assert(census.StrictOf(kept), qt.Equals, featureinventory.StrictRegistered)
}

// TestCommandCensus_HiddenFlagsAreMeasuredRatherThanListed pins the flag census.
//
// Hidden flags decide both directions of the flag coverage rule, so the set has
// to come from pflag's own bit. Measured: four distinct names across eight
// registrations, and three native commands carry the same pair rather than one
// command carrying four.
func TestCommandCensus_HiddenFlagsAreMeasuredRatherThanListed(t *testing.T) {
	c := qt.New(t)
	census := shippedCensus(c)

	registrations, hidden := hiddenFlagRegistrations(census)

	c.Assert(registrations, qt.Equals, 8)
	c.Assert(hidden, qt.HasLen, 4)
	c.Assert(hidden, qt.Contains, "atlas-project-config")
	c.Assert(hidden, qt.Contains, "atlas-project-var")
	c.Assert(hidden, qt.Contains, "dry-run")
	c.Assert(hidden, qt.Contains, "file")
}

// TestCommandCensus_TheFlagSetIsTheTreeNotTheHelp pins the seven commands whose
// help prints no flag block while they register four flags each.
//
// It is the measurement behind reading the tree rather than `--help`: on those
// seven, help is a strict subset of the flag set, so a flag census built on help
// would report that `ptah-compat schema push --var` does not exist.
func TestCommandCensus_TheFlagSetIsTheTreeNotTheHelp(t *testing.T) {
	paths := []string{
		"migrate push", "schema push",
		"schema plan approve", "schema plan list", "schema plan pull", "schema plan push", "schema plan rm",
	}

	for _, path := range paths {
		t.Run(path, func(t *testing.T) {
			c := qt.New(t)
			census := shippedCensus(c)
			cmd, found := census.Lookup(featureinventory.TreeCompat, path)
			c.Assert(found, qt.IsTrue)
			for _, flag := range []string{"config", "env", "var", "help"} {
				_, registered := cmd.Flags[flag]
				c.Assert(registered, qt.IsTrue, qt.Commentf("`ptah-compat %s` registers --%s and the census missed it", path, flag))
			}
		})
	}
}

// constructedPaths walks a root the way the Phase 1 audit did: over
// cmd.Commands() as the constructor returned it, with none of the initializers
// ExecuteC runs.
func constructedPaths(root *cobra.Command) []string {
	var paths []string
	var visit func(cmd *cobra.Command, parent string)
	visit = func(cmd *cobra.Command, parent string) {
		path := ""
		if cmd.Parent() != nil {
			path = parent + " " + cmd.Name()
			path = trimLeadingSpace(path)
		}
		paths = append(paths, path)
		for _, sub := range cmd.Commands() {
			visit(sub, path)
		}
	}
	visit(root, "")
	return paths
}

// missingFrom lists the shipped paths a constructed walk did not produce.
func missingFrom(constructed []string, shipped []featureinventory.Command) []string {
	have := make(map[string]bool)
	for _, path := range constructed {
		have[path] = true
	}
	var missing []string
	for _, cmd := range shipped {
		if !have[cmd.Path] {
			missing = append(missing, cmd.Path)
		}
	}
	return missing
}

// The helpers below keep the conditionals out of the test bodies, which
// scripts/check-test-style.sh requires. Each takes the collection and answers a
// question about it, rather than taking a bool and choosing with it.

// countLeaves counts the commands that register no subcommands.
func countLeaves(commands []featureinventory.Command) int {
	count := 0
	for _, cmd := range commands {
		if cmd.Leaf {
			count++
		}
	}
	return count
}

// hiddenFlagRegistrations counts every hidden flag registration across two
// trees, and lists the distinct names.
func hiddenFlagRegistrations(census *featureinventory.Census) (int, []string) {
	registrations := 0
	seen := make(map[string]bool)
	var names []string
	for _, tree := range []featureinventory.Tree{featureinventory.TreeNative, featureinventory.TreeCompat} {
		for _, cmd := range census.OfTree(tree) {
			for name, flag := range cmd.Flags {
				if !flag.Hidden {
					continue
				}
				registrations++
				if !seen[name] {
					seen[name] = true
					names = append(names, name)
				}
			}
		}
	}
	sort.Strings(names)
	return registrations, names
}

// trimLeadingSpace drops the leading blanks a joined path picks up at the root.
func trimLeadingSpace(text string) string {
	return strings.TrimLeft(text, " ")
}
