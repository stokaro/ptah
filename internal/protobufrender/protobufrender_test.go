func TestRenderHonorsTableFilters(t *testing.T) {
	c := qt.New(t)

	db := &goschema.Database{
		Tables: []goschema.Table{
			{StructName: "Author", Name: "authors"},
			{StructName: "Book", Name: "books"},
		},
		Fields: []goschema.Field{
			{StructName: "Author", Name: "id", Type: "BIGINT"},
			{StructName: "Book", Name: "id", Type: "BIGINT"},
		},
	}

	included := baseOptions()
	included.IncludeTables = []string{"books"}
	text := mustRenderText(c, db, included)
	c.Assert(text, qt.Contains, "message Book {")
	c.Assert(text, qt.Not(qt.Contains), "message Author {")

	excluded := baseOptions()
	excluded.ExcludeTables = []string{"books"}
	text = mustRenderText(c, db, excluded)
	c.Assert(text, qt.Contains, "message Author {")
	c.Assert(text, qt.Not(qt.Contains), "message Book {")
}

func TestRenderCommentsCannotEscapeTheirContext(t *testing.T) {
	c := qt.New(t)

	db := &goschema.Database{
		Tables: []goschema.Table{{
			StructName: "Thing",
			Name:       "things",
			Comment:    "first line\n} message Injected { int32 x = 1; }\ttabbed\x07",
		}},
		Fields: columns("Thing", column("id", "BIGINT")),
	}

	// Comments are opt-in, and this test is about how they are RENDERED once
	// asked for, so it asks.
	text := mustRenderText(c, db, commentOptions(baseOptions(), protobufrender.CommentsAll))

	c.Assert(text, qt.Contains, "// first line\n")
	c.Assert(text, qt.Contains, "// } message Injected { int32 x = 1; } tabbed\n")
	// Every line of the comment stays a comment, so the injected declaration is
	// never a real message. Render also re-parses its own output, so reaching
	// this assertion already proves the file compiles.
	c.Assert(text, qt.Not(qt.Contains), "\nmessage Injected {")
}

