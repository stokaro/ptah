func fileNameForTable(table schemamodel.Table) string {
	name := table.QualifiedName()
	if name == "" {
		name = table.StructName
	}
	return sanitizeFileName(name) + ".go"
}

func isSafeFileName(name string) bool {
	return name == filepath.Base(name) && name != "." && name != ".." && !filepath.IsAbs(name)
}

func sanitizeFileName(name string) string {
	name = strings.ToLower(strings.TrimSpace(name))
	name = strings.ReplaceAll(name, ".", "_")
	var builder strings.Builder
	for _, r := range name {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '_' {
			builder.WriteRune(r)
			continue
		}
		builder.WriteByte('_')
	}
	result := strings.Trim(builder.String(), "_")
	if result == "" {
		return "schema"
	}
	return result
}

func exportedIdentifier(name string) string {
	return upperFirst(identifierFromName(name))
}

func unexportedIdentifier(name string) string {
	return lowerFirst(identifierFromName(name))
}

func identifierFromName(name string) string {
	if hasUppercase(name) && token.IsIdentifier(name) && !token.Lookup(name).IsKeyword() {
		return name
	}
	parts := strings.FieldsFunc(name, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	if len(parts) == 0 {
		parts = []string{"value"}
	}
	var builder strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		runes := []rune(strings.ToLower(part))
		builder.WriteRune(unicode.ToUpper(runes[0]))
		for _, r := range runes[1:] {
			builder.WriteRune(r)
		}
	}
	result := builder.String()
	if result == "" {
		result = "Value"
	}
	if unicode.IsDigit([]rune(result)[0]) {
		result = "N" + result
	}
	if token.Lookup(result).IsKeyword() {
		result += "Value"
	}
	return result
}

func lowerFirst(name string) string {
	if name == "" {
		return name
	}
	runes := []rune(name)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes)
}

func upperFirst(name string) string {
	if name == "" {
		return name
	}
	runes := []rune(name)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

func hasUppercase(name string) bool {
	for _, r := range name {
		if unicode.IsUpper(r) {
			return true
		}
	}
	return false
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if value != "" {
			return value
		}
	}
	return ""
}

