//go:build integration

package integration_test

import (
	"context"
	"encoding/json"
	"fmt"
	"testing"
	"time"

	qt "github.com/frankban/quicktest"

	"ptah.run/internal/atlasreport"
	"ptah.run/internal/atlasurl"
	"ptah.run/internal/dbtarget"
)

// A schema account can see the tables in two databases but cannot read the
// role catalog. A grant on only one side must not produce a full-sync claim.
func TestMySQLFamilySchemaDiffNamesUnreadGrantsE2E(t *testing.T) {
	for _, engine := range mysqlServerEngines {
		t.Run(engine.name, func(t *testing.T) {
			c := qt.New(t)
			account := newMySQLServerAccount(c, engine.admin, []string{"left", "right"}, []string{"left", "right"})
			left, right := account.names["left"], account.names["right"]
			for _, database := range []string{left, right} {
				_, err := account.admin.ExecContext(c.Context(), "CREATE TABLE `"+database+"`.t (id int PRIMARY KEY)")
				c.Assert(err, qt.IsNil)
			}
			role := fmt.Sprintf("ptah_grant_coverage_%d", time.Now().UnixNano()%1_000_000_000)
			_, err := account.admin.ExecContext(c.Context(), "CREATE ROLE `"+role+"`")
			c.Assert(err, qt.IsNil)
			c.Cleanup(func() {
				_, dropErr := account.admin.ExecContext(context.Background(), "DROP ROLE IF EXISTS `"+role+"`")
				c.Check(dropErr, qt.IsNil)
			})
			// #nosec G202 -- Both identifiers come from names generated by this test.
			_, err = account.admin.ExecContext(c.Context(), "GRANT SELECT ON `"+left+"`.t TO `"+role+"`")
			c.Assert(err, qt.IsNil)
			adminURL := dbtarget.URL(c, engine.admin)
			adminLeft, err := atlasurl.WithDatabaseName(adminURL, left)
			c.Assert(err, qt.IsNil)
			adminRight, err := atlasurl.WithDatabaseName(adminURL, right)
			c.Assert(err, qt.IsNil)
			adminOut := runPtahNative(c, "schema", "diff", "--from", adminLeft, "--to", adminRight)
			c.Assert(adminOut, qt.Contains, "REVOKE SELECT")

			out := runPtahNative(c, "schema", "diff", "--from", account.url+left, "--to", account.url+right)
			c.Assert(out, qt.Contains, "No changes found in the visible scope")
			c.Assert(out, qt.Contains, "--from roles and grants")
			c.Assert(out, qt.Contains, "--to roles and grants")
			c.Assert(out, qt.Not(qt.Contains), "Schemas are synced")

			jsonOut := runPtahNative(c, "schema", "diff", "--format", "json", "--from", account.url+left,
				"--to", account.url+right)
			var document struct {
				Limits []atlasreport.SchemaDiffLimit `json:"comparison_limits"`
			}
			c.Assert(json.Unmarshal([]byte(jsonOut), &document), qt.IsNil, qt.Commentf("%s", jsonOut))
			c.Assert(document.Limits, qt.DeepEquals, []atlasreport.SchemaDiffLimit{
				{Side: "--from", Kind: "roles and grants", Reason: "the source did not describe this kind"},
				{Side: "--to", Kind: "roles and grants", Reason: "the source did not describe this kind"},
			})

			hidden := fmt.Sprintf("ptah_hidden_coverage_%d", time.Now().UnixNano()%1_000_000_000)
			createMySQLDatabase(c, c.Context(), account.admin, hidden)
			c.Cleanup(func() { dropMySQLDatabase(c, context.Background(), account.admin, hidden) })
			serverOut := runPtahNative(c, "schema", "diff", "--from", account.url, "--to", account.url)
			c.Assert(serverOut, qt.Contains, "--from database list")
			c.Assert(serverOut, qt.Contains, "--to database list")
			c.Assert(serverOut, qt.Not(qt.Contains), "Schemas are synced")
		})
	}
}
