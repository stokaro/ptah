const (
	// identityColumnRead prints the identity generation and the default of column n of
	// public.parent as the server does.
	identityColumnRead = "SELECT coalesce(identity_generation, '') || ' | ' || coalesce(column_default, '') || ' | ' || is_nullable " +
		"FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'parent' AND column_name = 'n'"
	// identityColumnNext takes the next value the column draws.
	identityColumnNext = "INSERT INTO parent (id) VALUES (1000) RETURNING n"
	// identityColumnPlain, identityColumnByDefault and identityColumnAlways declare n.
	identityColumnPlain     = "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint NOT NULL);\n"
	identityColumnByDefault = "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY);\n"
	identityColumnAlways    = "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED ALWAYS AS IDENTITY);\n"
)

// TestSchemaApplyIdentityColumnE2E_HappyPath declares an identity that differs from the
// one the database holds. The comparison read the two as synced. Each row reads the
// column back, and a second run finds nothing to do.
func TestSchemaApplyIdentityColumnE2E_HappyPath(t *testing.T) {
	tests := []struct{ name, built, desired, want string }{
		{name: "identity against a plain type", built: identityColumnByDefault, desired: identityColumnPlain, want: " |  | NO"},
		{name: "an always identity against a plain type", built: identityColumnAlways, desired: identityColumnPlain, want: " |  | NO"},
		{
			name:    "identity against a nullable column",
			built:   identityColumnAlways,
			desired: "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint);\n",
			want:    " |  | YES",
		},
		{
			name:    "identity against a default",
			built:   identityColumnAlways,
			desired: "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint NOT NULL DEFAULT 7);\n",
			want:    " | 7 | NO",
		},
		{name: "a plain type against identity", built: identityColumnPlain, desired: identityColumnByDefault, want: "BY DEFAULT |  | NO"},
		{
			name:    "a nullable column against identity",
			built:   "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint);\n",
			desired: identityColumnAlways,
			want:    "ALWAYS |  | NO",
		},
		{
			name:    "a default against identity",
			built:   "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint NOT NULL DEFAULT 7);\n",
			desired: identityColumnByDefault,
			want:    "BY DEFAULT |  | NO",
		},
		{name: "by default against always", built: identityColumnByDefault, desired: identityColumnAlways, want: "ALWAYS |  | NO"},
		{name: "always against by default", built: identityColumnAlways, desired: identityColumnByDefault, want: "BY DEFAULT |  | NO"},
		{name: "the same identity, control", built: identityColumnAlways, desired: identityColumnAlways, want: "ALWAYS |  | NO"},
		{name: "plain against plain, control", built: identityColumnPlain, desired: identityColumnPlain, want: " |  | NO"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			target := databaseBuiltFrom(c, test.built)

			run := keyedApply(c, target, test.desired)

			c.Assert(run.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", run.Stdout, run.Stderr))
			c.Assert(columnKeyString(c, target, identityColumnRead), qt.Equals, test.want)
			again := keyedApply(c, target, test.desired)
			c.Assert(again.Stdout, qt.Contains, "Schema is synced")
		})
	}
}

// TestSchemaApplyIdentityColumnE2E_TheSequenceMovesPastTheRows gives a populated column
// an identity. A sequence that starts at the beginning collides with the rows the table
// holds at the next insert. Each row takes the next value the column draws.
func TestSchemaApplyIdentityColumnE2E_TheSequenceMovesPastTheRows(t *testing.T) {
	const declared = "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY);\n"
	tests := []struct {
		name, rows, desired string
		want                int
	}{
		{name: "no rows", desired: declared, want: 1},
		{name: "rows", rows: "INSERT INTO parent VALUES (1, 1), (2, 5);\n", desired: declared, want: 6},
		{name: "rows below the first value", rows: "INSERT INTO parent VALUES (1, -5), (2, 0);\n", desired: declared, want: 1},
		{
			name:    "a declared start past the rows",
			rows:    "INSERT INTO parent VALUES (1, 5);\n",
			desired: "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100));\n",
			want:    100,
		},
		{
			name:    "rows past a declared start",
			rows:    "INSERT INTO parent VALUES (1, 500);\n",
			desired: "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100));\n",
			want:    501,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			target := databaseBuiltFrom(c, identityColumnPlain+test.rows)

			run := keyedApply(c, target, test.desired)

			c.Assert(run.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", run.Stdout, run.Stderr))
			c.Assert(readInt(c, target, identityColumnNext), qt.Equals, test.want)
		})
	}
}

// TestSchemaApplyIdentityColumnE2E_CockroachDB plans the same changes on CockroachDB,
// whose serial column reads back as unique_rowid() rather than a sequence.
func TestSchemaApplyIdentityColumnE2E_CockroachDB(t *testing.T) {
	tests := []struct{ name, built, desired, want string }{
		{name: "identity against a plain type", built: identityColumnByDefault, desired: identityColumnPlain, want: " | NULL | NO"},
		{name: "a plain type against identity", built: identityColumnPlain, desired: identityColumnByDefault, want: "BY DEFAULT | NULL | NO"},
		{
			name:    "a nullable column against identity",
			built:   "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint);\n",
			desired: identityColumnByDefault,
			want:    "BY DEFAULT | NULL | NO",
		},
		{name: "by default against always", built: identityColumnByDefault, desired: identityColumnAlways, want: "ALWAYS | NULL | NO"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			target, _ := cockroachVisibilityDatabase(c, c.Context(), test.built)

			run := keyedApply(c, target, test.desired)

			c.Assert(run.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", run.Stdout, run.Stderr))
			again := keyedApply(c, target, test.desired)
			c.Assert(again.Stdout, qt.Contains, "Schema is synced")
		})
	}
}

// TestSchemaApplyIdentityColumnE2E_GoAnnotation takes the identity from a Go annotation
// that leaves NOT NULL out, over a nullable column.
func TestSchemaApplyIdentityColumnE2E_GoAnnotation(t *testing.T) {
	c := qt.New(t)
	target := databaseBuiltFrom(c, "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint);\n")
	root := c.TempDir()
	c.Assert(os.WriteFile(filepath.Join(root, "entities.go"), []byte(`package entities

//ptah:schema:table name="parent"
type Parent struct {
	//ptah:schema:field name="id" type="BIGINT" primary="true"
	ID int64
	//ptah:schema:field name="n" type="BIGINT" identity_generation="ALWAYS"
	N int64
}
`), 0o600), qt.IsNil)

	run := runPtahIn(c, "schema", "apply", "--db-url", target, "--root-dir", root, "--auto-approve")

	c.Assert(run.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", run.Stdout, run.Stderr))
	c.Assert(columnKeyString(c, target, identityColumnRead), qt.Equals, "ALWAYS |  | NO")
	again := runPtahIn(c, "schema", "apply", "--db-url", target, "--root-dir", root, "--auto-approve")
	c.Assert(again.Stdout, qt.Contains, "Schema is synced")
}

// TestMigrationsIdentityColumnE2E_TheRollbackRestoresTheColumn rolls each change back and
// reads the column as it stood.
func TestMigrationsIdentityColumnE2E_TheRollbackRestoresTheColumn(t *testing.T) {
	tests := []struct{ name, built, desired, wantUp, wantDown string }{
		{name: "the identity leaves", built: identityColumnAlways, desired: identityColumnPlain, wantUp: " |  | NO", wantDown: "ALWAYS |  | NO"},
		{name: "the identity arrives", built: identityColumnPlain, desired: identityColumnAlways, wantUp: "ALWAYS |  | NO", wantDown: " |  | NO"},
		{name: "the generation changes", built: identityColumnByDefault, desired: identityColumnAlways, wantUp: "ALWAYS |  | NO", wantDown: "BY DEFAULT |  | NO"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			target := databaseBuiltFrom(c, test.built)
			dir := filepath.Join(c.TempDir(), "migrations")
			c.Assert(os.MkdirAll(dir, 0o750), qt.IsNil)
			schema := filepath.Join(c.TempDir(), "schema.sql")
			c.Assert(os.WriteFile(schema, []byte(test.desired), 0o600), qt.IsNil)

			generated := runPtahIn(c, "migrations", "generate", "--db-url", target, "--schema-file", schema, "--migrations-dir", dir, "--name", "identity")
			c.Assert(generated.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", generated.Stdout, generated.Stderr))
			up := runPtahIn(c, "migrations", "up", "--db-url", target, "--migrations-dir", dir, "--allow-destructive")
			c.Assert(up.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", up.Stdout, up.Stderr))
			c.Assert(columnKeyString(c, target, identityColumnRead), qt.Equals, test.wantUp)

			down := runPtahIn(c, "migrations", "down", "--db-url", target, "--migrations-dir", dir, "--target", "0", "--confirm")

			c.Assert(down.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", down.Stdout, down.Stderr))
			c.Assert(columnKeyString(c, target, identityColumnRead), qt.Equals, test.wantDown)
		})
	}
}
