package integration_test

import (
	"context"
	"database/sql"
	"fmt"
	"path/filepath"
	"testing"
	"time"

	qt "github.com/frankban/quicktest"
	_ "github.com/jackc/pgx/v5/stdlib" // registers the pgx driver for database/sql

	"ptah.run/internal/dbtarget"
)

// A derived rollback compares the target with a dev database that holds what
// the migration directory makes at the target version. A grant the target
// holds and the migrations do not make, to a role the migrations do not
// manage, is not the rollback's to take: the dev database never had it. Read
// as a whole answer, the dev database's silence about the grant planned its
// REVOKE, and through the YDB provider every grant of the database root to
// its built-in groups. The rollback here still drops what version 2 made, and
// that drop is the control: the plan ran.
func TestMigrationsDownPlanLeavesAGrantTheMigrationsDoNotMakeE2E(t *testing.T) {
	c := qt.New(t)
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	dbURL := dbtarget.URL(c, dbtarget.PostgreSQL)
	repoRoot := e2eRepoRoot(t)
	binaryPath := filepath.Join(t.TempDir(), "ptah")
	buildPtah(c, ctx, repoRoot, binaryPath)

	adminDB, err := sql.Open("pgx", dbURL)
	c.Assert(err, qt.IsNil)
	defer adminDB.Close()
	testID := time.Now().UnixNano()
	targetDBName := fmt.Sprintf("ptah_down_plan_grant_target_e2e_%d", testID)
	shadowDBName := fmt.Sprintf("ptah_down_plan_grant_shadow_e2e_%d", testID)
	role := fmt.Sprintf("ptah_down_plan_reader_%d", testID)
	createE2EDatabase(c, ctx, adminDB, targetDBName)
	defer dropE2EDatabase(c, context.Background(), adminDB, targetDBName)
	createE2EDatabase(c, ctx, adminDB, shadowDBName)
	defer dropE2EDatabase(c, context.Background(), adminDB, shadowDBName)
	// #nosec G202 -- the role name is generated by this test and quoted by quoteE2EIdent.
	_, err = adminDB.ExecContext(ctx, "CREATE ROLE "+quoteE2EIdent(role))
	c.Assert(err, qt.IsNil)
	targetDBURL := replaceDatabaseName(c, dbURL, targetDBName)
	shadowDBURL := replaceDatabaseName(c, dbURL, shadowDBName)
	targetDB, err := sql.Open("pgx", targetDBURL)
	c.Assert(err, qt.IsNil)
	defer func() {
		// The grant goes before the role, which PostgreSQL refuses to drop
		// while a database still grants it something.
		// #nosec G202 -- the role name is generated by this test and quoted by quoteE2EIdent.
		_, _ = targetDB.ExecContext(context.Background(), "REVOKE ALL ON SCHEMA public FROM "+quoteE2EIdent(role))
		_ = targetDB.Close()
		// #nosec G202 -- the role name is generated by this test and quoted by quoteE2EIdent.
		_, _ = adminDB.ExecContext(context.Background(), "DROP ROLE IF EXISTS "+quoteE2EIdent(role))
	}()

	migrationsDir := writeDownPlanMigrations(c, t.TempDir())
	upOutput, err := runPtah(ctx, repoRoot, binaryPath,
		"migrations", "up", "--db-url", targetDBURL, "--migrations-dir", migrationsDir)
	c.Assert(err, qt.IsNil, qt.Commentf("%s", upOutput))
	// #nosec G202 -- the role name is generated by this test and quoted by quoteE2EIdent.
	_, err = targetDB.ExecContext(ctx, "GRANT USAGE ON SCHEMA public TO "+quoteE2EIdent(role))
	c.Assert(err, qt.IsNil)

	downOutput, err := runPtah(ctx, repoRoot, binaryPath,
		"migrations", "down", "--plan",
		"--db-url", targetDBURL,
		"--shadow-db", shadowDBURL,
		"--migrations-dir", migrationsDir,
		"--target", "1",
		"--confirm")
	var usage bool
	usageErr := targetDB.QueryRowContext(ctx, `SELECT has_schema_privilege($1, 'public', 'USAGE')`, role).Scan(&usage)
	var posts sql.NullString
	postsErr := targetDB.QueryRowContext(ctx, `SELECT to_regclass('public.posts')::text`).Scan(&posts)

	c.Assert(err, qt.IsNil, qt.Commentf("%s", downOutput))
	c.Assert(downOutput, qt.Not(qt.Contains), "REVOKE")
	c.Assert(usageErr, qt.IsNil)
	c.Assert(usage, qt.IsTrue)
	c.Assert(postsErr, qt.IsNil)
	c.Assert(posts.Valid, qt.IsFalse)
}
