// catalogColumnSequences is what the database holds of the sequences and of the
// columns that draw from them: each sequence with its options, and each column
// with its type, its default, its identity and the sequence it owns.
const catalogColumnSequences = `
SELECT string_agg(line, E'\n' ORDER BY line) FROM (
    SELECT format('sequence %s.%s %s start %s min %s increment %s max %s cache %s cycle %s',
        schemaname, sequencename, data_type, start_value, min_value, increment_by, max_value, cache_size, cycle) AS line
    FROM pg_sequences WHERE schemaname IN ('public', 'app')
    UNION ALL
    SELECT format('column %s.%s.%s %s not null %s identity %s default %s owns %s',
        n.nspname, c.relname, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, a.attidentity,
        pg_get_expr(d.adbin, d.adrelid), pg_get_serial_sequence(format('%I.%I', n.nspname, c.relname), a.attname))
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE n.nspname IN ('public', 'app') AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped
      AND c.relname <> 'ptah_schema_apply_log'
) AS held`

// columnSequences is what the scratch database holds of its column sequences.
func (s scratch) columnSequences(c *qt.C) string {
	c.Helper()
	var held string
	c.Assert(s.conn.QueryRowContext(c.Context(), catalogColumnSequences).Scan(&held), qt.IsNil)
	return held
}

// TestAPlainDumpOfColumnSequencesValidatesE2E validates the dump, which states
// each serial column as four statements and each identity column as two:
// CREATE SEQUENCE, ALTER SEQUENCE ... OWNED BY and ALTER COLUMN ... SET
// DEFAULT, and ALTER COLUMN ... ADD GENERATED ... AS IDENTITY.
func TestAPlainDumpOfColumnSequencesValidatesE2E(t *testing.T) {
	c := qt.New(t)

	out, err := ptah("schema", "validate", "--dialect", "postgres", "--schema-file", writeSchema(c, columnSequencesDump))

	c.Assert(err, qt.IsNil, qt.Commentf("%s", out))
	c.Assert(strings.Count(columnSequencesDump, " OWNED BY "), qt.Equals, 6)
	c.Assert(strings.Count(columnSequencesDump, " ADD GENERATED "), qt.Equals, 3)
}

// TestAPlainDumpOfColumnSequencesReadsSyncedE2E reads the dump against the
// database it describes: no sequence a column owns is planned again, and no
// identity is dropped.
func TestAPlainDumpOfColumnSequencesReadsSyncedE2E(t *testing.T) {
	c := qt.New(t)
	dev := newScratch(c)
	dev.exec(c, columnSequencesBuilt)

	plan := dev.plan(c, columnSequencesDump, "public,app")
	drift := dev.drift(c, columnSequencesDump, "public,app")

	c.Assert(plan, qt.Contains, "Schema is synced")
	c.Assert(drift, qt.Contains, "No schema drift detected")
}

// TestAPlainDumpOfColumnSequencesBuildsItsDatabaseE2E applies the dump to an
// empty database. The plan creates the two sequences that are not a serial
// type's own, the one no column owns and the one with another increment, and
// builds every other sequence with its column. The database it builds holds
// what the dumped one holds, option for option, and the dump reads synced
// against it.
func TestAPlainDumpOfColumnSequencesBuildsItsDatabaseE2E(t *testing.T) {
	c := qt.New(t)
	source := newScratch(c)
	source.exec(c, columnSequencesBuilt)
	dev := newScratch(c)

	planned := dev.plan(c, columnSequencesDump, "public,app")
	out, err := ptah("schema", "apply", "--db-url", dev.url, "--schema-file", writeSchema(c, columnSequencesDump),
		"--schemas", "public,app", "--auto-approve")

	c.Assert(err, qt.IsNil, qt.Commentf("%s", out))
	c.Assert(strings.Count(planned, "CREATE SEQUENCE"), qt.Equals, 2, qt.Commentf("%s", planned))
	c.Assert(planned, qt.Contains, `CREATE SEQUENCE \"public\".\"free_seq\"`)
	c.Assert(planned, qt.Contains, `CREATE SEQUENCE \"public\".\"s_opt_id_seq\"`)
	c.Assert(dev.columnSequences(c), qt.Equals, source.columnSequences(c))
	c.Assert(dev.plan(c, columnSequencesDump, "public,app"), qt.Contains, "Schema is synced")
}

// TestAPlainDumpWithAReplicaIdentity_FailurePathE2E validates a dump that sets
// a table's replica identity. Ptah does not model one, so the statement is
// refused by name with what to do about it.
func TestAPlainDumpWithAReplicaIdentity_FailurePathE2E(t *testing.T) {
	c := qt.New(t)

	out, err := ptah("schema", "validate", "--dialect", "postgres", "--schema-file", writeSchema(c, replicaIdentityDump))

	c.Assert(err, qt.IsNotNil)
	c.Assert(out, qt.Contains, "unsupported ALTER TABLE public.r_full REPLICA IDENTITY FULL: "+
		"Ptah does not model a table's replica identity; delete the statement from the schema file, "+
		"and set the replica identity in a migration where a database needs it")
}
