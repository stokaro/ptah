// TestSchemaApplySerialAgainstIdentityE2E_CockroachDB runs the pairs on CockroachDB, whose
// serial column holds unique_rowid() and owns no sequence.
func TestSchemaApplySerialAgainstIdentityE2E_CockroachDB(t *testing.T) {
	tests := []struct {
		name, built, desired, want string
		synced                     bool
	}{
		{name: "an always identity against serial", built: serialIdentityAlways, desired: serialIdentitySerial, want: " | unique_rowid()"},
		{name: "serial against an always identity", built: serialIdentitySerial, desired: serialIdentityAlways, want: "ALWAYS | "},
		{name: "by default against serial", built: serialIdentityByDefault, desired: serialIdentitySerial, want: "BY DEFAULT | ", synced: true},
		{name: "serial against by default", built: serialIdentitySerial, desired: serialIdentityByDefault, want: " | unique_rowid()", synced: true},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			target, _ := cockroachVisibilityDatabase(c, c.Context(), test.built)

			run := keyedApply(c, target, test.desired)

			c.Assert(run.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", run.Stdout, run.Stderr))
			c.Assert(columnKeyString(c, target, "SELECT coalesce(identity_generation, '') || ' | ' || coalesce(column_default, '') "+
				"FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'parent' AND column_name = 'n'"), qt.Equals, test.want)
			again := keyedApply(c, target, test.desired)
			c.Assert(again.Stdout, qt.Contains, "Schema is synced")
		})
	}
}

// TestMigrationsSerialAgainstIdentityE2E_TheRollbackRestoresTheColumn rolls each direction
// back: the column reads as it stood, and its next value follows the rows.
func TestMigrationsSerialAgainstIdentityE2E_TheRollbackRestoresTheColumn(t *testing.T) {
	tests := []struct{ name, built, rows, desired, wantDown string }{
		{
			name:     "serial against an always identity",
			built:    serialIdentitySerial,
			rows:     "INSERT INTO parent (id, n) VALUES (1, 41);\n",
			desired:  serialIdentityAlways,
			wantDown: " | nextval('parent_n_seq'::regclass)",
		},
		{
			name:     "an always identity against serial",
			built:    serialIdentityAlways,
			rows:     "INSERT INTO parent (id, n) OVERRIDING SYSTEM VALUE VALUES (1, 41);\n",
			desired:  serialIdentitySerial,
			wantDown: "ALWAYS | ",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			target := databaseBuiltFrom(c, test.built+test.rows)
			dir := filepath.Join(c.TempDir(), "migrations")
			c.Assert(os.MkdirAll(dir, 0o750), qt.IsNil)
			schema := filepath.Join(c.TempDir(), "schema.sql")
			c.Assert(os.WriteFile(schema, []byte(test.desired), 0o600), qt.IsNil)

			generated := runPtahIn(c, "migrations", "generate", "--db-url", target, "--schema-file", schema, "--migrations-dir", dir, "--name", "serial")
			c.Assert(generated.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", generated.Stdout, generated.Stderr))
			up := runPtahIn(c, "migrations", "up", "--db-url", target, "--migrations-dir", dir, "--allow-destructive")
			c.Assert(up.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", up.Stdout, up.Stderr))

			down := runPtahIn(c, "migrations", "down", "--db-url", target, "--migrations-dir", dir, "--target", "0", "--confirm")

			c.Assert(down.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", down.Stdout, down.Stderr))
			c.Assert(columnKeyString(c, target, serialIdentityRead), qt.Equals, test.wantDown)
			c.Assert(readInt(c, target, serialIdentityNext), qt.Equals, 42)
		})
	}
}
