//go:build integration

package integration_test

import (
	"os"
	"path/filepath"
	"testing"

	qt "github.com/frankban/quicktest"
)

const (
	// serialIdentityRead prints the identity generation and the default of column n of
	// public.parent as the server does.
	serialIdentityRead = "SELECT coalesce(identity_generation, '') || ' | ' || coalesce(column_default, '') " +
		"FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'parent' AND column_name = 'n'"
	// serialIdentityNext takes the next value the column draws.
	serialIdentityNext = "INSERT INTO parent (id) VALUES (1000) RETURNING n"
	// serialIdentitySerial, serialIdentityByDefault and serialIdentityAlways declare n.
	serialIdentitySerial    = "CREATE TABLE parent (id bigint PRIMARY KEY, n bigserial);\n"
	serialIdentityByDefault = "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED BY DEFAULT AS IDENTITY);\n"
	serialIdentityAlways    = "CREATE TABLE parent (id bigint PRIMARY KEY, n bigint GENERATED ALWAYS AS IDENTITY);\n"
)

// TestSchemaApplySerialAgainstIdentityE2E_HappyPath declares a serial column over an
// identity generated ALWAYS, and the reverse. The two read as synced, and only one of them
// takes a value an insert names. Each row reads the column back, takes the next value
// past the rows, and a second run finds nothing to do.
func TestSchemaApplySerialAgainstIdentityE2E_HappyPath(t *testing.T) {
	tests := []struct {
		name, built, rows, desired, want string
	}{
		{
			name:    "an always identity against serial",
			built:   serialIdentityAlways,
			rows:    "INSERT INTO parent (id, n) OVERRIDING SYSTEM VALUE VALUES (1, 41);\n",
			desired: serialIdentitySerial,
			want:    " | nextval('parent_n_seq'::regclass)",
		},
		{
			name:    "serial against an always identity",
			built:   serialIdentitySerial,
			rows:    "INSERT INTO parent (id, n) VALUES (1, 41);\n",
			desired: serialIdentityAlways,
			want:    "ALWAYS | ",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			target := databaseBuiltFrom(c, test.built+test.rows)

			run := keyedApply(c, target, test.desired)

			c.Assert(run.ExitCode, qt.Equals, 0, qt.Commentf("stdout:\n%s\nstderr:\n%s", run.Stdout, run.Stderr))
			c.Assert(columnKeyString(c, target, serialIdentityRead), qt.Equals, test.want)
			again := keyedApply(c, target, test.desired)
			c.Assert(again.Stdout, qt.Contains, "Schema is synced")
			c.Assert(readInt(c, target, serialIdentityNext), qt.Equals, 42)
		})
	}
}

// TestSchemaApplySerialAgainstIdentityE2E_ComparedEqual holds the pairs that compare
