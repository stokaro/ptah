// guardedAcrossFiles each split a guarded repeat across files: the second
// file declares again what the first created. PostgreSQL 15.19 runs the files
// in order, as one script.
var guardedAcrossFiles = []struct {
	name  string
	files []string
}{
	{name: "a view replaced", files: []string{"CREATE TABLE t (a int, b int);\nCREATE VIEW v AS SELECT a FROM t;", "CREATE OR REPLACE VIEW v AS SELECT b AS a FROM t;"}},
	{
		name: "a function replaced",
		files: []string{"CREATE FUNCTION f() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$;",
			"CREATE OR REPLACE FUNCTION f() RETURNS int LANGUAGE sql AS $$ SELECT 2 $$;"},
	},
	{
		name: "a trigger replaced",
		files: []string{"CREATE TABLE t (a int);\n" +
			"CREATE FUNCTION trg() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;\n" +
			"CREATE TRIGGER tr BEFORE INSERT ON t FOR EACH ROW EXECUTE FUNCTION trg();",
			"CREATE OR REPLACE TRIGGER tr BEFORE UPDATE ON t FOR EACH ROW EXECUTE FUNCTION trg();"},
	},
	{name: "a table declared again", files: []string{"CREATE TABLE t (a int);", "CREATE TABLE IF NOT EXISTS t (a int, b int);"}},
	{name: "a table written with its schema, then without", files: []string{"CREATE TABLE public.t (a int);", "CREATE TABLE IF NOT EXISTS t (a int, b int);"}},
	{name: "a sequence declared again", files: []string{"CREATE SEQUENCE s START 5;", "CREATE SEQUENCE IF NOT EXISTS s START 10;"}},
	{
		name: "a table dropped and created again, its index guarded in a later file",
		files: []string{"CREATE TABLE t (a int);\nCREATE INDEX i ON t (a);",
			"DROP TABLE t;\nCREATE TABLE t (a int);\nCREATE INDEX IF NOT EXISTS i ON t (a);"},
	},
	{
		name:  "a dropped unique column's key name, guarded in a later file",
		files: []string{"CREATE TABLE t (a int UNIQUE, b int);", "ALTER TABLE t DROP COLUMN a;\nCREATE INDEX IF NOT EXISTS t_a_key ON t (b);"},
	},
	{
		name: "an identity column's named sequence, the default name guarded in a later file",
		files: []string{"CREATE TABLE t (id int GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME myseq), b int);",
			"CREATE SEQUENCE IF NOT EXISTS t_id_seq START 100;"},
	},
	{name: "a primary key's index guarded in a later file", files: []string{"CREATE TABLE t (id int PRIMARY KEY, b int);", "CREATE INDEX IF NOT EXISTS t_pkey ON t (b);"}},
}

// writeGuardedFiles writes files as 01.sql, 02.sql … in a new directory and
// returns the directory, the paths, and the script they make together.
func writeGuardedFiles(c *qt.C, files []string) (dir string, paths []string, script string) {
	c.Helper()
	dir = c.TempDir()
	for index, sql := range files {
		path := filepath.Join(dir, fmt.Sprintf("%02d.sql", index+1))
		c.Assert(os.WriteFile(path, []byte(sql+"\n"), 0o600), qt.IsNil)
		paths = append(paths, path)
		script += sql + "\n"
	}
	return dir, paths, script
}

// TestPostgresGuardedDeclarationsAcrossFilesDiffEmptyE2E builds a database
// from the files run in order and diffs it with them, read as a schema
// directory and as one --to source per file: nothing changes, because a
// later file's guard reaches what an earlier file declared.
func TestPostgresGuardedDeclarationsAcrossFilesDiffEmptyE2E(t *testing.T) {
	for _, test := range guardedAcrossFiles {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			dir, paths, script := writeGuardedFiles(c, test.files)
			target := databaseBuiltFrom(c, script)
			sources := []string{"--to", "file://" + filepath.ToSlash(dir)}
			perFile := make([]string, 0, 2*len(paths))
			for _, path := range paths {
				perFile = append(perFile, "--to", "file://"+filepath.ToSlash(path))
			}

			code, stdout, stderr := runAsOneRun(c, nativeTree, append([]string{"schema", "diff", "--from", target}, sources...)...)
			perFileCode, perFileStdout, perFileStderr := runAsOneRun(c, nativeTree, append([]string{"schema", "diff", "--from", target}, perFile...)...)

			c.Assert(code, qt.Equals, 0, qt.Commentf("stderr:\n%s", stderr))
			c.Assert(stdout, qt.Equals, "Schemas are synced, no changes to be made.\n")
			c.Assert(perFileCode, qt.Equals, 0, qt.Commentf("stderr:\n%s", perFileStderr))
			c.Assert(perFileStdout, qt.Equals, "Schemas are synced, no changes to be made.\n")
		})
	}
}

// TestPostgresGuardedDeclarationsDiffEmptyE2E builds a database from each file
// and diffs it with the file: nothing changes, because the reader skips what
// the server skipped and keeps what the server replaced the first definition
// with.
func TestPostgresGuardedDeclarationsDiffEmptyE2E(t *testing.T) {
	for _, test := range guardedDeclarations {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			schema := filepath.Join(c.TempDir(), "schema.sql")
			c.Assert(os.WriteFile(schema, []byte(test.sql+"\n"), 0o600), qt.IsNil)

			code, stdout, stderr := runAsOneRun(c, nativeTree, "schema", "diff",
				"--from", databaseBuiltFrom(c, test.sql), "--to", "file://"+filepath.ToSlash(schema))

			c.Assert(code, qt.Equals, 0, qt.Commentf("stderr:\n%s", stderr))
			c.Assert(stdout, qt.Equals, "Schemas are synced, no changes to be made.\n")
		})
	}
}

// TestPostgresGuardedDeclarationsReplaySyncedE2E is the same files on
// ptah-compat: a migration directory holding the file, replayed on a dev
// database, is synced with the file. The test server is declared disposable,
// since the replay refuses a routine it cannot confine to the dev database
// otherwise.
func TestPostgresGuardedDeclarationsReplaySyncedE2E(t *testing.T) {
	for _, test := range guardedDeclarations {
		t.Run(test.name, func(t *testing.T) {
			c := qt.New(t)
			envbooltest.Set(devdocker.DisposableServerEnvVar, "1")(c)
			dir, schema := writeRewrittenMigrationProject(c, test.sql, test.sql)
			dev, _ := scratchReplayDatabase(c)

			code, stdout, stderr := runAsOneRun(c, compatTree, "migrate", "diff", "--dir", "file://"+filepath.ToSlash(dir),
				"--to", "file://"+filepath.ToSlash(schema), "--dev-url", dev)

			c.Assert(code, qt.Equals, 0, qt.Commentf("stderr:\n%s", stderr))
			c.Assert(stdout, qt.Equals, "The migration directory is synced with the desired state, no changes to be made\n")
		})
	}
}
