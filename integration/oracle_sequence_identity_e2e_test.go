// TestOracleUsedSequenceE2E applies a sequence, draws two values from it, and
// applies the same file again. Oracle keeps no START WITH and reports
// LAST_NUMBER, which the first NEXTVAL moves past the start to the end of the
// cached block, so the second apply finds the schema synced. Compared as a
// declared start, the second apply answers "changing the start counter is not
// rendered for Oracle", and so does every later one. A changed increment on
// the used sequence is applied and converges. A start the counter has not
// reached is still a change, and the plan refuses it.
func TestOracleUsedSequenceE2E(t *testing.T) {
	c := qt.New(t)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	binary := filepath.Join(c.TempDir(), "ptah")
	buildPtah(c, ctx, e2eRepoRoot(t), binary)
	_, dbURL, conn := oracleCaseSensitiveAccount(c, ctx)
	declared := writeDeclaredSchema(c, "CREATE SEQUENCE sq START WITH 1 INCREMENT BY 1;\n")
	stepped := writeDeclaredSchemaFile(c, "stepped.sql", "CREATE SEQUENCE sq START WITH 1 INCREMENT BY 5;\n")
	unreached := writeDeclaredSchemaFile(c, "unreached.sql", "CREATE SEQUENCE sq START WITH 1000 INCREMENT BY 5;\n")
	apply := func(schema string) (string, string, error) {
		return runCLIProcess(ctx, c.TempDir(), binary, "schema", "apply", "--db-url", dbURL, "--schema-file", schema, "--auto-approve")
	}

	stdout, stderr, err := apply(declared)
	c.Assert(err, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", stdout, stderr))
	drawn := accountNames(c, ctx, conn, "SELECT TO_CHAR(sq.NEXTVAL) FROM dual CONNECT BY LEVEL <= 2")
	again, stderr, err := apply(declared)
	c.Assert(drawn, qt.DeepEquals, []string{"1", "2"})
	c.Assert(err, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", again, stderr))
	c.Assert(again, qt.Contains, "Schema is synced")

	stdout, stderr, err = apply(stepped)
	c.Assert(err, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", stdout, stderr))
	c.Assert(stdout, qt.Contains, "ALTER SEQUENCE sq INCREMENT BY 5;")
	c.Assert(accountNames(c, ctx, conn, "SELECT TO_CHAR(increment_by) FROM user_sequences WHERE sequence_name = 'SQ'"),
		qt.DeepEquals, []string{"5"})
	again, stderr, err = apply(stepped)
	c.Assert(err, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", again, stderr))
	c.Assert(again, qt.Contains, "Schema is synced")

	stdout, stderr, err = apply(unreached)
	c.Assert(err, qt.IsNotNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", stdout, stderr))
	c.Assert(stderr, qt.Contains, "ALTER SEQUENCE sq: changing the start counter is not rendered for Oracle")
}

// TestOracleIdentityColumnE2E applies identity columns declared ALWAYS, BY
// DEFAULT, as SERIAL and as AUTO_INCREMENT, none of them NOT NULL, and applies
// the file again.
// Oracle builds each NOT NULL, so the second apply finds the schema synced;
// compared as declared, it plans MODIFY (id NUMBER(10) NULL), which Oracle
// answers with ORA-01451. The column declared ALWAYS is generated ALWAYS and
// refuses an insert that names it with ORA-32795, where a column written BY
// DEFAULT takes the value.
func TestOracleIdentityColumnE2E(t *testing.T) {
	c := qt.New(t)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	binary := filepath.Join(c.TempDir(), "ptah")
	buildPtah(c, ctx, e2eRepoRoot(t), binary)
	_, dbURL, conn := oracleCaseSensitiveAccount(c, ctx)
	schema := writeDeclaredSchema(c,
		"CREATE TABLE ia (id NUMBER(10) GENERATED ALWAYS AS IDENTITY, n NUMBER(10));\n"+
			"CREATE TABLE ib (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY, n NUMBER(10));\n"+
			"CREATE TABLE ic (id SERIAL, n NUMBER(10));\n"+
			"CREATE TABLE id (id NUMBER(10) AUTO_INCREMENT, n NUMBER(10));\n")
	apply := []string{"schema", "apply", "--db-url", dbURL, "--schema-file", schema, "--auto-approve"}

	stdout, stderr, err := runCLIProcess(ctx, c.TempDir(), binary, apply...)
	again, againErr, err2 := runCLIProcess(ctx, c.TempDir(), binary, apply...)
	_, named := conn.ExecContext(ctx, "INSERT INTO ia (id, n) VALUES (7, 1)")

	c.Assert(err, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", stdout, stderr))
	c.Assert(err2, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", again, againErr))
	c.Assert(again, qt.Contains, "Schema is synced")
	c.Assert(accountNames(c, ctx, conn,
		"SELECT i.table_name || ' ' || i.generation_type || ' ' || c.nullable FROM user_tab_identity_cols i "+
			"JOIN user_tab_columns c ON c.table_name = i.table_name AND c.column_name = i.column_name ORDER BY 1"),
		qt.DeepEquals, []string{"IA ALWAYS N", "IB BY DEFAULT N", "IC BY DEFAULT N", "ID BY DEFAULT N"})
	c.Assert(named, qt.ErrorMatches, `(?s).*ORA-32795.*`)
	runAsAccount(c, ctx, conn, []string{"INSERT INTO ib (id, n) VALUES (7, 1)"})
}

// TestOracleIdentityChangeE2E applies identity columns, draws a value from
// each that takes one, and applies a file that changes the identity of each:
//
//   - ga, BY DEFAULT to ALWAYS, and gs, ALWAYS to SERIAL, change generation in
//     place, and the counter goes on from where it was;
//   - gb, gn and gk declare a plain column, so the identity is dropped; gb is
//     nullable after, gn takes its NOT NULL, a wider type and a default in a
//     second statement, and gk stays NOT NULL as the key column.
//
// The next apply finds the schema synced. Without the comparison of the
// generation, the plan leaves ga and gs as they are, and gb fails every apply
// with ORA-01451. An identity declared on an existing plain column is refused
// before any statement runs, since Oracle has no statement for it.
func TestOracleIdentityChangeE2E(t *testing.T) {
	c := qt.New(t)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()
	binary := filepath.Join(c.TempDir(), "ptah")
	buildPtah(c, ctx, e2eRepoRoot(t), binary)
	_, dbURL, conn := oracleCaseSensitiveAccount(c, ctx)
	built := writeDeclaredSchemaFile(c, "built.sql",
		"CREATE TABLE ga (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY, n NUMBER(10));\n"+
			"CREATE TABLE gs (id NUMBER(10) GENERATED ALWAYS AS IDENTITY, n NUMBER(10));\n"+
			"CREATE TABLE gb (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY, n NUMBER(10));\n"+
			"CREATE TABLE gn (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY, n NUMBER(10));\n"+
			"CREATE TABLE gk (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n NUMBER(10));\n"+
			"CREATE TABLE gc (id NUMBER(10) NOT NULL, n NUMBER(10));\n")
	const unchanged = "CREATE TABLE ga (id NUMBER(10) GENERATED ALWAYS AS IDENTITY, n NUMBER(10));\n" +
		"CREATE TABLE gs (id SERIAL, n NUMBER(10));\n" +
		"CREATE TABLE gb (id NUMBER(10), n NUMBER(10));\n" +
		"CREATE TABLE gn (id NUMBER(19) DEFAULT 7 NOT NULL, n NUMBER(10));\n" +
		"CREATE TABLE gk (id NUMBER(10) PRIMARY KEY, n NUMBER(10));\n"
	changed := writeDeclaredSchemaFile(c, "changed.sql", unchanged+"CREATE TABLE gc (id NUMBER(10) NOT NULL, n NUMBER(10));\n")
	gained := writeDeclaredSchemaFile(c, "gained.sql", unchanged+"CREATE TABLE gc (id NUMBER(10) AUTO_INCREMENT, n NUMBER(10));\n")
	apply := func(schema string) (string, string, error) {
		return runCLIProcess(ctx, c.TempDir(), binary, "schema", "apply", "--db-url", dbURL, "--schema-file", schema, "--auto-approve")
	}

	stdout, stderr, err := apply(built)
	c.Assert(err, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", stdout, stderr))
	runAsAccount(c, ctx, conn, []string{"INSERT INTO ga (n) VALUES (1)", "INSERT INTO gs (n) VALUES (1)"})
	stdout, stderr, err = apply(changed)
	again, againErr, err2 := apply(changed)
	runAsAccount(c, ctx, conn, []string{"INSERT INTO ga (n) VALUES (2)", "INSERT INTO gs (n) VALUES (2)", "INSERT INTO gs (id, n) VALUES (9, 3)"})
	_, named := conn.ExecContext(ctx, "INSERT INTO ga (id, n) VALUES (9, 3)")
	refused, refusal, err3 := apply(gained)

	c.Assert(err, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", stdout, stderr))
	c.Assert(stdout, qt.Contains, "ALTER TABLE ga MODIFY (id NUMBER(10) GENERATED ALWAYS AS IDENTITY);\n")
	c.Assert(stdout, qt.Contains, "ALTER TABLE gs MODIFY (id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY);\n")
	c.Assert(stdout, qt.Contains, "ALTER TABLE gb MODIFY (id NUMBER(10) DROP IDENTITY);\n")
	c.Assert(stdout, qt.Contains, "ALTER TABLE gn MODIFY (id NUMBER(19) DROP IDENTITY);\nALTER TABLE gn MODIFY (id DEFAULT 7 NOT NULL);\n")
	c.Assert(stdout, qt.Contains, "ALTER TABLE gk MODIFY (id NUMBER(10) DROP IDENTITY);\n")
	c.Assert(err2, qt.IsNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", again, againErr))
	c.Assert(again, qt.Contains, "Schema is synced")
	c.Assert(accountNames(c, ctx, conn, "SELECT table_name || ' ' || generation_type FROM user_tab_identity_cols ORDER BY 1"),
		qt.DeepEquals, []string{"GA ALWAYS", "GS BY DEFAULT"})
	c.Assert(accountNames(c, ctx, conn,
		"SELECT table_name || ' ' || data_type || '(' || data_precision || ') ' || nullable FROM user_tab_columns WHERE column_name = 'ID' ORDER BY 1"),
		qt.DeepEquals, []string{"GA NUMBER(10) N", "GB NUMBER(10) Y", "GC NUMBER(10) N", "GK NUMBER(10) N", "GN NUMBER(19) N", "GS NUMBER(10) N"})
	c.Assert(accountNames(c, ctx, conn,
		"SELECT table_name || ' ' || NVL(TRIM(data_default_vc), '-') FROM user_tab_columns WHERE column_name = 'ID' AND identity_column = 'NO' ORDER BY 1"),
		qt.DeepEquals, []string{"GB -", "GC -", "GK -", "GN 7"})
	c.Assert(accountNames(c, ctx, conn, "SELECT TO_CHAR(id) FROM ga ORDER BY n"), qt.DeepEquals, []string{"1", "2"})
	c.Assert(accountNames(c, ctx, conn, "SELECT TO_CHAR(id) FROM gs ORDER BY n"), qt.DeepEquals, []string{"1", "2", "9"})
	c.Assert(named, qt.ErrorMatches, `(?s).*ORA-32795.*`)
	c.Assert(err3, qt.IsNotNil, qt.Commentf("stdout:\n%s\nstderr:\n%s", refused, refusal))
	c.Assert(refusal, qt.Contains, `render modified column gc.id: unsupported feature: oracle: an existing column does not become an identity column (ORA-30673), and column "id" declares one`)
	c.Assert(accountNames(c, ctx, conn, "SELECT identity_column FROM user_tab_columns WHERE table_name = 'GC' AND column_name = 'ID'"),
		qt.DeepEquals, []string{"NO"})
}
